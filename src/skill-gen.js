/**
 * Generates the agent-facing instruction text shipped with DocsLit:
 *
 *   - generateAuthorSkill()   skills/docslit-author.md (committed; `npm run skills`
 *                             regenerates it, a test fails if it is stale)
 *   - readMigrateSkill()      skills/docslit-migrate.md (hand-written)
 *   - generateAgentsBlock()   the project-specific AGENTS.md block
 *
 * The component reference is rendered from src/component-manifest.js so it can
 * never drift from the code. Prose lives in src/skill-templates/*.md.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { getComponentManifest, getCategoryLabels } from './component-manifest.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const PACKAGE_ROOT = path.join(__dirname, '..');
export const SKILLS_DIR = path.join(PACKAGE_ROOT, 'skills');
const TEMPLATE_DIR = path.join(__dirname, 'skill-templates');

function template(name) {
  return fs.readFileSync(path.join(TEMPLATE_DIR, name), 'utf8');
}

/** Wrap text in a code fence long enough not to collide with fences inside it. */
function fenced(text, lang = '') {
  const longest = Math.max(0, ...[...text.matchAll(/`{3,}/g)].map((m) => m[0].length));
  const fence = '`'.repeat(Math.max(3, longest + 1));
  return `${fence}${lang}\n${text}\n${fence}`;
}

function renderAttribute(a) {
  const bits = [];
  if (a.values?.length) bits.push(a.values.join(' | '));
  else bits.push(a.type);
  if (a.required) bits.push('required');
  if (a.default != null) bits.push(`default \`${a.default}\``);
  return `  - \`${a.name}\` (${bits.join(', ')}): ${a.description}`;
}

function renderComponent(c) {
  const lines = [`#### \`${c.tag}\``, '', c.description, ''];
  const body = c.selfClosing ? 'none (self-closing)' : c.content === 'none' ? 'none' : `${c.content}${c.contentDescription ? `. ${c.contentDescription}` : ''}`;
  lines.push(`- Body: ${body}`);
  if (c.parents?.length) lines.push(`- Parent: ${c.parents.map((t) => `\`${t}\``).join(', ')}`);
  if (c.children?.length) lines.push(`- Children: ${c.children.map((t) => `\`${t}\``).join(', ')}`);
  const attrs = c.attributes.filter((a) => a.name !== 'theme');
  if (attrs.length) {
    lines.push('- Attributes:');
    for (const a of attrs) lines.push(renderAttribute(a));
  } else {
    lines.push('- Attributes: none');
  }
  lines.push('', fenced(c.example, 'markdown'), '');
  return lines.join('\n');
}

export function renderComponentReference(manifest = getComponentManifest()) {
  const labels = getCategoryLabels();
  const order = [];
  const byCat = new Map();
  for (const c of manifest) {
    if (!byCat.has(c.category)) { byCat.set(c.category, []); order.push(c.category); }
    byCat.get(c.category).push(c);
  }
  const out = [];
  for (const cat of order) {
    out.push(`### ${labels[cat] || cat}`, '');
    for (const c of byCat.get(cat)) out.push(renderComponent(c));
  }
  return out.join('\n');
}

export function generateAuthorSkill() {
  return template('author.md').replace('%%COMPONENT_REFERENCE%%', renderComponentReference());
}

export function readMigrateSkill() {
  return fs.readFileSync(path.join(SKILLS_DIR, 'docslit-migrate.md'), 'utf8');
}

/** Split `---` YAML frontmatter off a skill. Handles the simple `key: value` form we generate. */
export function splitSkill(text) {
  const m = /^---\n([\s\S]*?)\n---\n+([\s\S]*)$/.exec(text);
  if (!m) return { meta: {}, body: text };
  const meta = {};
  for (const line of m[1].split('\n')) {
    const kv = /^([\w-]+):\s*(.*)$/.exec(line);
    if (kv) meta[kv[1]] = kv[2];
  }
  return { meta, body: m[2] };
}

/**
 * The project-specific AGENTS.md block (without the marker comments).
 * @param {{ docsDir?: string, sidebarMode?: 'explicit'|'auto'|'mixed', groups?: string[], versions?: string[],
 *           locales?: string[], defaultLocale?: string, openapi?: boolean, hasMcp?: boolean, skillInstalled?: boolean,
 *           name?: string }} [project]
 */
export function generateAgentsBlock(project = {}) {
  const docsDir = project.docsDir || 'docs';
  const facts = [];
  facts.push(`- Pages: \`${docsDir}/**/*.md\`. A page id is its path without \`.md\` (\`guides/setup\` is \`${docsDir}/guides/setup.md\`).`);
  if (project.sidebarMode === 'auto') {
    facts.push('- Sidebar: fully autogenerated from the folder tree (`"sidebar": "auto"`). Create the file; do not edit the sidebar. Order with frontmatter `sidebar_position`, hide with `sidebar: false`.');
  } else if (project.sidebarMode === 'mixed') {
    facts.push('- Sidebar: some groups are autogenerated from folders (`autogenerate`), others list pages explicitly. `docslit new --group "<name>"` registers a page in an explicit group; files in an autogenerated folder appear on their own.');
  } else {
    const g = project.groups?.length ? ` Groups: ${project.groups.map((x) => `"${x}"`).join(', ')}.` : '';
    facts.push(`- Sidebar: explicit, in \`docslit.json\`. New pages must be added to a group (\`docslit new --group\` does it).${g}`);
  }
  if (project.versions?.length) facts.push(`- Versioned docs (git-branch based): ${project.versions.join(', ')}. Edit the branch for the version you mean to change.`);
  if (project.locales?.length) facts.push(`- i18n: default locale \`${project.defaultLocale || 'en'}\` in \`${docsDir}/\`; other locales (${project.locales.filter((l) => l !== (project.defaultLocale || 'en')).join(', ')}) in \`${docsDir}.<locale>/\`. Keep page ids identical across locales.`);
  if (project.openapi) facts.push('- An OpenAPI spec is configured. Endpoint pages come from `docslit openapi scaffold`; `<wc-endpoint ref="operationId">` fills from the spec. Do not hand-write what the spec already says.');
  facts.push('- Reusable snippets live in `' + docsDir + '/_reusables/` and are included with `<wc-include src="name.md" />`.');
  facts.push('- Commands: `docslit dev` (preview), `docslit build` (static site to `dist/`).');

  const newHint = project.sidebarMode === 'auto' ? ' (the file appears in the sidebar automatically)'
    : ' (add `--group "<sidebar group>"` to register it in the sidebar)';
  const skillHint = project.skillInstalled
    ? ', or read `.claude/skills/docslit-author/SKILL.md`'
    : ' (prints the complete component reference, generated from the CLI version you are running)';

  return template('agents-md.md')
    .replace(/%%DOCS_DIR%%/g, docsDir)
    .replace('%%PROJECT%%', `${facts.join('\n')}\n`)
    .replace('%%NEW_HINT%%', newHint)
    .replace('%%SKILL_HINT%%', skillHint)
    .trimEnd() + '\n';
}
