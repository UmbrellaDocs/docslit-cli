// Issue codes produced by checkMarkup (shared with `docslit validate`).
const MARKUP_CODES = new Set([
  'unclosed-tag', 'unexpected-closing-tag', 'malformed-tag', 'unknown-attribute', 'invalid-attribute-value',
  'missing-required-attribute', 'invalid-parent', 'invalid-child', 'self-closing-syntax',
]);

const RO = { readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: false };

/** Run fn with console.log/info/warn redirected to stderr so stdout stays pure JSON-RPC. */
export async function quiet(fn) {
  const saved = { log: console.log, info: console.info, warn: console.warn, debug: console.debug };
  const toErr = (...a) => console.error(...a);
  console.log = toErr; console.info = toErr; console.warn = toErr; console.debug = toErr;
  try {
    return await fn();
  } finally {
    Object.assign(console, saved);
  }
}

function summarize(issues) {
  return {
    errors: issues.filter((i) => i.level === 'error').length,
    warnings: issues.filter((i) => i.level === 'warning').length,
    infos: issues.filter((i) => i.level === 'info').length,
  };
}

async function optionalLint(dir) {
  try {
    const mod = await import('../lint.js');
    if (typeof mod.runLint !== 'function') return null;
    return await quiet(() => mod.runLint(dir));
  } catch {
    return null;
  }
}

function compactComponent(c) {
  return { tag: c.tag, category: c.category, description: c.description.split(/(?<=[.!?])\s/)[0] };
}

function componentsMarkdown() {
  const labels = getCategoryLabels();
  const out = ['# DocsLit components', ''];
  let cat = null;
  for (const c of getComponentManifest()) {
    if (c.category !== cat) { cat = c.category; out.push(`## ${labels[cat] || cat}`, ''); }
    const attrs = c.attributes.filter((a) => a.name !== 'theme').map((a) => `${a.name}${a.required ? '*' : ''}${a.values ? `=${a.values.join('|')}` : ''}`).join(', ');
    out.push(`- \`${c.tag}\`${c.selfClosing ? ' (self-closing)' : ''}: ${c.description.split(/(?<=[.!?])\s/)[0]}${attrs ? ` Attributes: ${attrs}.` : ''}${c.parents ? ` Parent: ${c.parents.join('|')}.` : ''}${c.children ? ` Children: ${c.children.join('|')}.` : ''}`);
  }
  out.push('', '(* = required) Use get_component { tag } for descriptions and examples.');
  return out.join('\n');
}

function themeSummary(config) {
  try {
    const r = resolveSiteThemeSync(config);
    return { theme: r.themeName, palette: r.paletteId, customColours: r.isCustom, appearance: r.appearance, strict: r.strict, availableThemes: listThemes().map((t) => t.id), availablePalettes: listPalettes().map((p) => p.id), hint: 'Change with `docslit theme use <theme> [--palette <p>]`; token reference: `docslit theme tokens --json`.' };
  } catch {
    return null;
  }
}

function detectFeatures(config, sidebarRaw) {
  const f = [];
  if (!config) return f;
  if (config.openapi) f.push('openapi');
  if (config.math !== false) f.push('math');
  if (config.pdf?.enabled) f.push('pdf');
  if (config.feedback) f.push('feedback');
  if (config.versions?.list?.length) f.push('versions');
  if (config.i18n?.locales?.length > 1) f.push('i18n');
  if (config.theme) f.push('theme');
  if (config.announcement) f.push('announcement');
  if (config.analytics) f.push('analytics');
  if (config.playground) f.push('playground');
  if (config.redirects && Object.keys(config.redirects).length) f.push('redirects');
  if (config.css) f.push('custom-css');
  if (config.attributes && Object.keys(config.attributes).length) f.push('global-variables');
  if (sidebarRaw === 'auto' || JSON.stringify(sidebarRaw || '').includes('"autogenerate"')) f.push('autogenerated-sidebar');
  return f;
}

function mergeFrontmatterFromContent(content) {
  const trimmed = String(content ?? '').replace(/^﻿/, '');
  if (!/^---\r?\n/.test(trimmed)) return { data: {}, body: trimmed };
  const parsed = safeFrontmatter(trimmed);
  if (parsed.error) throw new ToolError(`The content starts with a frontmatter block that is not valid YAML: ${parsed.error}. Pass title/description as arguments and send only the Markdown body in "content".`);
  return { data: parsed.data, body: parsed.content };
}

function ensureTrailingNewline(s) {
  return s.endsWith('\n') ? s : `${s}\n`;
}

