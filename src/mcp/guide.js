export const GUIDE_TOPICS = ['overview', 'frontmatter', 'config', 'components', 'reusables', 'openapi'];

const OVERVIEW = `# Writing DocsLit pages

DocsLit is a static docs generator: Markdown files in \`docs/\` plus \`wc-*\` web-component tags written directly in Markdown (no imports). Config lives in \`docslit.json\`.

## Workflow (use the MCP tools, do not guess)
1. \`get_project_info\` - site name, sidebar, features, existing pages.
2. \`search_docs\` / \`read_page\` - match the tone and structure of existing pages; avoid duplicating content.
3. \`list_components\` then \`get_component\` for any component you have not used - never invent tags or attributes.
4. Draft the Markdown, run \`check_markup\` on it, then \`create_page\` (new) or \`update_page\` (existing).
5. Fix every issue the tool returns, then \`validate\` the page. Finish with zero errors.

## Rules that prevent most mistakes
- A page id maps to a file: \`guides/setup\` -> \`docs/guides/setup.md\`. Ids are lower-case, hyphenated, no extension.
- Frontmatter needs \`title\`; add a one-sentence \`description\` (used for SEO, search and llms.txt).
- Start the body with a single \`# H1\` equal to the title, then \`##\` sections. Do not skip heading levels.
- Put a blank line before and after every block-level \`<wc-*>\` tag, and after an opening tag whose body is Markdown.
- Close every tag with \`</wc-x>\`. Never write \`<wc-x />\` (HTML custom elements do not self-close); the one exception is the compile-time \`<wc-include ... />\`.
- Use only attributes listed by \`get_component\`. Common slips: \`label\` (not \`title\`) on wc-tab/wc-code-tab, \`icon-name\` (not \`icon\`) on cards/tiles.
- Container components accept only specific children (wc-steps > wc-step, wc-tabs > wc-tab, wc-tiles > wc-tile|wc-card, wc-code-group > wc-code-tab, wc-fields > wc-field, wc-accordion-group > wc-accordion).
- Content of wc-code-block / wc-code-tab / wc-mermaid is raw text: no Markdown inside. Prefer plain fenced code blocks for code.
- Internal links: relative or root-based to existing pages; \`validate\` reports broken links and missing assets.
- A new page must be reachable: \`create_page\` adds it to the sidebar unless the sidebar is autogenerated.
- Use \`{{VARIABLE_NAME}}\` (UPPER_SNAKE_CASE) placeholders for values defined under \`attributes\` in docslit.json.
`;

const REUSABLES = `# Reusable snippets and variables

- Snippets live in \`docs/_reusables/\` (files and folders starting with "_" are never pages and never need a sidebar entry).
- Include one with \`<wc-include src="snippet.md" />\` (resolved under docs/_reusables; "_reusables/snippet.md" also works). It is compile-time, must be self-closing, and an included file cannot itself contain wc-include. Frontmatter in the snippet is ignored.
- Variables: define globally in docslit.json \`"attributes": {"PRODUCT": "Acme"}\` or per page in frontmatter \`attributes:\`; use \`{{PRODUCT}}\` in the body. Names must match [A-Z_][A-Z0-9_]*.
- \`<wc-var name="API_KEY" default="sk-..."></wc-var>\` renders an editable variable input in the page; \`{{API_KEY}}\` inside code blocks becomes click-to-edit.
- Pull code from real project files so examples cannot go stale: add \`file="examples/server.js" lines="10-25"\` (or \`region="name"\`) after the language on a fenced code block (an otherwise empty block); paths are relative to the project root.
- create_page can create snippets: use an id like "_reusables/prereqs" (no sidebar entry is added).
`;

const OPENAPI = `# OpenAPI-driven API reference

- Point docslit.json at the spec: \`"openapi": "openapi.yaml"\` or \`{"spec": "openapi.yaml", "overlay": "overlay.yaml"}\`.
- Generate one page per operation from the CLI: \`docslit openapi scaffold <spec.yaml> [--overlay overlay.yaml] [--new-only]\` (run it in the project root; it writes docs pages and sidebar entries). Re-run with --new-only to add only missing operations.
- In a hand-written page, reference an operation by operationId instead of retyping it: \`<wc-endpoint ref="getUser"></wc-endpoint>\` or give method + url explicitly. \`get_component wc-endpoint\` lists every attribute and the allowed children (wc-fields for parameters, wc-response-fields / wc-responses for results, wc-code-tab for request samples).
- Document parameters with \`<wc-fields>\`/\`<wc-field name type required>\`; field names are exactly the API's names; mark \`required\`, give \`default\`/\`enum\` when known.
- validate checks that wc-endpoint refs exist in the spec and lists undocumented operations.
- For a single endpoint page, use the \`document-api-endpoint\` prompt.
`;

function firstSentence(s = '') {
  const m = String(s).match(/^[\s\S]*?[.!?](?=\s|$)/);
  return (m ? m[0] : s).replace(/\s+/g, ' ').trim();
}

function propLine(name, spec) {
  let type = spec.type || (spec.oneOf ? spec.oneOf.map((o) => o.type).filter(Boolean).join('|') : '');
  if (Array.isArray(type)) type = type.join('|');
  if (spec.enum) type = spec.enum.map((v) => JSON.stringify(v)).join('|');
  return `- \`${name}\`${type ? ` (${type})` : ''}: ${firstSentence(spec.description)}`;
}

async function frontmatterTopic() {
  const s = await readSchema('frontmatter');
  const lines = Object.entries(s.properties).map(([k, v]) => propLine(k, v));
  return `# Page frontmatter

YAML between \`---\` lines at the top of each page. Only \`title\` is strongly recommended; unknown keys are ignored.

\`\`\`yaml
---
title: Install the CLI
description: Install DocsLit and verify the setup.
sidebar_title: Install
tag: Guide
readtime: 3 min read
updated: 2026-01-15
---
\`\`\`

${lines.join('\n')}

Full JSON Schema: get_schema { kind: "frontmatter" }.
`;
}

async function configTopic() {
  const s = await readSchema('config');
  const lines = Object.entries(s.properties).filter(([k]) => k !== '$schema').map(([k, v]) => propLine(k, v));
  return `# docslit.json

Project root config (JSON). Page ids in \`sidebar\` map to \`docs/<id>.md\`.

\`\`\`json
{
  "$schema": "https://unpkg.com/docslit/schema/docslit.schema.json",
  "name": "Acme Docs",
  "description": "Docs for Acme.",
  "url": "https://docs.acme.com",
  "sidebar": [
    { "group": "Getting Started", "pages": ["introduction", "quickstart"] },
    { "group": "Guides", "autogenerate": "guides" }
  ]
}
\`\`\`

Sidebar forms: explicit groups with \`pages\` (strings, nested {group,pages}), \`autogenerate\` (a docs/ subdirectory; pages appear automatically, ordered by \`sidebar_position\`), or the string \`"auto"\` for the whole tree. create_page only edits explicit groups.

Top-level keys:
${lines.join('\n')}

Full JSON Schema: get_schema { kind: "config" }.
`;
}

function componentsTopic() {
  const labels = getCategoryLabels();
  const by = new Map();
  for (const c of getComponentManifest()) {
    if (!by.has(c.category)) by.set(c.category, []);
    by.get(c.category).push(c);
  }
  const sections = [];
  for (const [cat, items] of by) {
    sections.push(`## ${labels[cat] || cat}\n${items.map((c) => `- \`${c.tag}\`: ${firstSentence(c.description)}`).join('\n')}`);
  }
  return `# Components

${sections.join('\n\n')}

Details for one tag (attributes, allowed values, nesting, example): get_component { tag }. Validate a draft: check_markup { markdown }.

Nesting cheat sheet: wc-steps > wc-step; wc-tabs > wc-tab (label=); wc-code-group > wc-code-tab (label=); wc-tiles > wc-tile|wc-card; wc-fields|wc-response-fields > wc-field; wc-accordion-group > wc-accordion; wc-files > wc-dir|wc-file; wc-versions > wc-version; wc-endpoint > wc-fields|wc-response-fields|wc-responses|wc-code-tab.
`;
}

/** Return the guide text for one topic. */
export async function getGuide(topic = 'overview') {
  switch (topic) {
    case 'overview': return OVERVIEW;
    case 'frontmatter': return frontmatterTopic();
    case 'config': return configTopic();
    case 'components': return componentsTopic();
    case 'reusables': return REUSABLES;
    case 'openapi': return OPENAPI;
    default: return null;
  }
}

