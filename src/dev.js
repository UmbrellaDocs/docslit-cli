import express from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import fs from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { pathExists } from './fs-helpers.js';
import { createServer } from 'http';
import { WebSocketServer } from 'ws';
import chokidar from 'chokidar';
import pc from 'picocolors';
import { loadConfig, getAllPageIds, getVersionConfig, getOpenAPIConfig, gitReadFile, getVersionNavigation } from './config.js';
import { pageNavMeta, walkPages, isSearchableMeta, collectHiddenIds, isNoindexMeta } from './navigation.js';
import { pageClientInfo, withApiTab } from './nav-chrome.js';
import { parseDoc } from './markdown.js';
import { sidebarLabel } from './sidebar.js';
import { katexDistDir } from './math.js';
import { parseFrontmatter } from './frontmatter.js';
import { renderShell } from './template.js';
import { resolveSiteTheme, parseThemeConfig } from './themes.js';
import { initHighlighter } from './highlighter.js';
import { normalizeBasePath, logoFiles } from './site-config.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

export async function dev({ port = 3000, themePicker = false } = {}) {
  const cwd = process.cwd();
  const config = await loadConfig(cwd);
  let siteTheme = await resolveSiteTheme(config, cwd);
  if (themePicker) siteTheme.picker = true;

  console.log(`\n  ${pc.bold('DocsLit')} dev server starting...\n`);

  let specData = null;
  let apiMeta = null;
  let resolveSpecRefs = null;
  let buildApiPageMarkdown = null;
  async function reloadSpec() {
    const openapiConfig = getOpenAPIConfig(config);
    if (!openapiConfig?.spec) return;
    try {
      const openapi = await import('./openapi.js');
      const spec = await openapi.loadSpec(
        path.resolve(cwd, openapiConfig.spec),
        openapiConfig.overlay ? path.resolve(cwd, openapiConfig.overlay) : null,
      );
      specData = openapi.getEndpoints(spec);
      apiMeta = openapi.getApiMeta(spec);
      resolveSpecRefs = openapi.resolveSpecRefs;
      buildApiPageMarkdown = openapi.buildApiPageMarkdown;
      console.log(`  ${pc.green('✓')} Loaded OpenAPI spec (${specData.length} endpoints)`);
    } catch (e) {
      console.log(`  ${pc.yellow('⚠')} Failed to load OpenAPI spec: ${e.message}`);
    }
  }
  await reloadSpec();

  function getRuntimeAttributes(cfg, version = null, branch = null) {
    const attrs = { ...(cfg.attributes || {}) };
    attrs.DOCSLIT_VERSION = version || 'unversioned';
    attrs.DOCSLIT_BRANCH = branch || 'working-tree';
    return attrs;
  }

  const app = express();
  const server = createServer(app);
  const wss = new WebSocketServer({ server });

  const clients = new Set();
  wss.on('connection', (ws) => {
    clients.add(ws);
    ws.on('close', () => clients.delete(ws));
  });

  let titleMap = {};
  let navMeta = {};
  // docslit.json / autogenerated sidebars changed: swap the fresh config in (dropping stale keys such as removed tabs).
  function replaceConfig(fresh) {
    for (const k of Object.keys(config)) delete config[k];
    Object.assign(config, fresh);
  }
  const navConfig = () => withApiTab(config, !!specData);
  async function rebuildTitleMap(cfg) {
    const map = {};
    const nmap = {};
    const ids = getAllPageIds(cfg);
    await Promise.all(ids.map(async (id) => {
      const mdPath = path.join(cwd, 'docs', `${id}.md`);
      try {
        const raw = await fs.readFile(mdPath, 'utf8');
        const { data } = parseFrontmatter(raw);
        const label = sidebarLabel(data);
        if (label) map[id] = label;
        const nm = pageNavMeta(data);
        if (Object.keys(nm).length) nmap[id] = nm;
      } catch {}
    }));
    titleMap = map;
    navMeta = nmap;
  }
  await rebuildTitleMap(config);

  const parseCache = new Map();
  const codeDeps = new Set();
  let watcher = null;
  async function cachedParseDoc(mdPath, raw, opts) {
    const stat = await fs.stat(mdPath);
    const cached = parseCache.get(mdPath);
    if (cached && cached.mtimeMs === stat.mtimeMs) return cached.result;
    const result = await parseDoc(raw, opts);
    // Watch code files imported via ```lang file="..." so edits rebuild the page.
    for (const dep of result.preprocess?.dependencies || []) {
      if (!codeDeps.has(dep) && !dep.startsWith(path.join(cwd, 'docs') + path.sep)) {
        codeDeps.add(dep);
        watcher?.add(dep);
      }
    }
    parseCache.set(mdPath, { mtimeMs: stat.mtimeMs, result });
    return result;
  }

  function broadcast(event) {
    const msg = JSON.stringify(event);
    for (const client of clients) {
      if (client.readyState === 1) client.send(msg);
    }
  }

  function themeFilePath(cfg) {
    const parsed = parseThemeConfig(cfg);
    return parsed.file ? path.resolve(cwd, parsed.file) : null;
  }

  async function reloadSiteTheme(cfg) {
    siteTheme = await resolveSiteTheme(cfg, cwd);
    if (themePicker) siteTheme.picker = true;
  }

  // Watch for changes
  const docsDir = path.join(cwd, 'docs');
  const componentsDir = path.join(cwd, 'components');
  const watchPaths = [
    // chokidar >=4 has no glob support: watch directories and filter in the handler.
    path.join(cwd, 'docs'),
    path.join(cwd, 'docslit.json'),
    path.join(cwd, 'components'),
  ];
  const themePath = themeFilePath(config);
  if (themePath) watchPaths.push(themePath);
  const openapiConf = getOpenAPIConfig(config);
  if (openapiConf?.spec) watchPaths.push(path.join(cwd, openapiConf.spec));
  if (openapiConf?.overlay) watchPaths.push(path.join(cwd, openapiConf.overlay));

  watcher = chokidar.watch(watchPaths, { ignoreInitial: true });

  watcher.on('all', async (event, filePath) => {
    const isCodeDep = codeDeps.has(path.resolve(filePath));
    const docsRel = path.relative(path.join(cwd, 'docs'), filePath);
    const inDocs = !docsRel.startsWith('..') && !path.isAbsolute(docsRel);
    const relevant = isCodeDep
      || (inDocs && (filePath.endsWith('.md') || path.basename(filePath) === '_category.json'))
      || filePath.endsWith('docslit.json')
      || path.relative(path.join(cwd, 'components'), filePath).split(path.sep)[0] !== '..'
      || (themeFilePath(config) && path.resolve(filePath) === themeFilePath(config))
      || (openapiConf?.spec && filePath.endsWith(openapiConf.spec))
      || (openapiConf?.overlay && filePath.endsWith(openapiConf.overlay));
    if (!relevant) return;
    const rel = path.relative(cwd, filePath);
    console.log(`  ${pc.cyan('~')} ${rel} changed — reloading`);
    if (filePath.includes('_reusables') || isCodeDep) {
      parseCache.clear();
    } else {
      parseCache.delete(filePath);
    }
    // Autogenerated sidebars: new/removed/renamed pages, sidebar_position edits and _category.json change the sidebar.
    const sidebarSourceChanged = inDocs && !filePath.includes('_reusables')
      && (filePath.endsWith('.md') || path.basename(filePath) === '_category.json');
    if (sidebarSourceChanged) {
      replaceConfig(await loadConfig(cwd));
    }
    if (filePath.endsWith('docslit.json') || (themeFilePath(config) && path.resolve(filePath) === themeFilePath(config))) {
      replaceConfig(await loadConfig(cwd));
      try {
        await reloadSiteTheme(config);
      } catch (e) {
        console.log(`  ${pc.yellow('!')} Theme reload failed: ${e.message}`);
      }
    }
    if (openapiConf?.spec && (filePath.endsWith(openapiConf.spec) || (openapiConf.overlay && filePath.endsWith(openapiConf.overlay)))) {
      await reloadSpec();
    }
    if (filePath.endsWith('.md') || filePath.endsWith('docslit.json')) {
      await rebuildTitleMap(config);
    }
    broadcast({ type: 'reload' });
  });

  // API: list pages
  app.get('/api/pages', async (req, res) => {
    const freshConfig = await loadConfig(cwd);
    res.json({ config: freshConfig });
  });

  // API: serve a single markdown page (versioned and unversioned)
  // Uses {*path} wildcard to support nested page IDs like commands/check
  app.get('/api/page/{*path}', async (req, res) => {
    try {
      const segments = Array.isArray(req.params.path) ? req.params.path.join('/') : req.params.path;
      const vc = getVersionConfig(config);

      let id, version;
      if (vc) {
        const parts = segments.split('/');
        const maybeVersion = parts[0];
        const entry = vc.list.find(v => v.version === maybeVersion);
        if (entry) {
          version = maybeVersion;
          id = parts.slice(1).join('/');
        } else {
          id = segments;
        }
      } else {
        id = segments;
      }

      if (!id) return res.status(400).json({ error: 'Missing page id' });

      if (version) {
        const entry = vc.list.find(v => v.version === version);
        const docsDir = path.join(cwd, 'docs');
        const mdPath = path.resolve(docsDir, `${id}.md`);
        if (mdPath.startsWith(docsDir + path.sep) && await pathExists(mdPath)) {
          const raw = await fs.readFile(mdPath, 'utf8');
          let { meta, html } = await cachedParseDoc(mdPath, raw, {
            docsRoot: path.join(cwd, 'docs'),
            pagePath: mdPath,
            globalAttributes: getRuntimeAttributes(config, entry.version, entry.branch),
          });
          if (specData) html = resolveSpecRefs(html, specData);
          return res.json({ id, meta, html, nav: { ...pageClientInfo(navConfig(), id, meta), noindex: isNoindexMeta(meta) } });
        }
        const readFromVersion = async (absPath) => {
          const relFromDocs = path.relative(path.join(cwd, 'docs'), absPath).replace(/\\/g, '/');
          const gitPath = `docs/${relFromDocs}`;
          const fromGit = await gitReadFile(entry.branch, gitPath, cwd);
          if (fromGit == null) throw new Error(`Include target not found in ${entry.branch}: ${gitPath}`);
          return fromGit;
        };
        const existsFromVersion = async (absPath) => {
          const relFromDocs = path.relative(path.join(cwd, 'docs'), absPath).replace(/\\/g, '/');
          const gitPath = `docs/${relFromDocs}`;
          const fromGit = await gitReadFile(entry.branch, gitPath, cwd);
          return fromGit != null;
        };
        const raw = await gitReadFile(entry.branch, `docs/${id}.md`, cwd);
        if (raw) {
          let { meta, html } = await parseDoc(raw, {
            docsRoot: path.join(cwd, 'docs'),
            pagePath: `docs/${id}.md@${entry.branch}`,
            globalAttributes: getRuntimeAttributes(config, entry.version, entry.branch),
            readFile: readFromVersion,
            pathExists: existsFromVersion,
            strictFsSafety: false,
          });
          if (specData) html = resolveSpecRefs(html, specData);
          return res.json({ id, meta, html, nav: { ...pageClientInfo(navConfig(), id, meta), noindex: isNoindexMeta(meta) } });
        }
        return res.status(404).json({ error: `Page "${id}" not found in version ${version}` });
      }

      const docsDir = path.join(cwd, 'docs');
      const mdPath = path.resolve(docsDir, `${id}.md`);
      if (!mdPath.startsWith(docsDir + path.sep)) {
        return res.status(400).json({ error: 'Invalid page id' });
      }
      if (!await pathExists(mdPath)) {
        return res.status(404).json({ error: `Page "${id}" not found` });
      }
      const raw = await fs.readFile(mdPath, 'utf8');
      const defaultVersion = vc?.default || null;
      const defaultEntry = vc?.list?.find(v => v.version === defaultVersion);
      let { meta, html } = await cachedParseDoc(mdPath, raw, {
        docsRoot: path.join(cwd, 'docs'),
        pagePath: mdPath,
        globalAttributes: getRuntimeAttributes(config, defaultVersion, defaultEntry?.branch || null),
      });
      if (specData) html = resolveSpecRefs(html, specData);
      res.json({ id, meta, html, nav: { ...pageClientInfo(navConfig(), id, meta), noindex: isNoindexMeta(meta) } });
    } catch (e) {
      res.status(500).json({ error: e.message });
    }
  });

  // Serve raw markdown source for AI agents: GET /page.md or GET /docs/page.md
  app.get(/\.md$/, async (req, res) => {
    let slug = req.path.replace(/\.md$/, '').replace(/^\//, '');
    const vc = getVersionConfig(config);
    let requestedVersion = null;
    if (vc) {
      for (const v of vc.list) {
        if (slug.startsWith(v.version + '/')) {
          requestedVersion = v.version;
          slug = slug.slice(v.version.length + 1);
          break;
        }
      }
    }
    slug = slug.replace(/^docs\//, '');
    const docsDir = path.join(cwd, 'docs');
    const mdPath = path.resolve(docsDir, `${slug}.md`);
    if (!mdPath.startsWith(docsDir + path.sep)) {
      return res.status(400).send('Invalid path');
    }

    const versionEntry = requestedVersion
      ? vc?.list?.find(v => v.version === requestedVersion)
      : vc?.list?.find(v => v.version === vc.default);
    let mdRaw = null;
    let parseOpts = {
      docsRoot: path.join(cwd, 'docs'),
      pagePath: mdPath,
      globalAttributes: getRuntimeAttributes(config, requestedVersion || vc?.default || null, versionEntry?.branch || null),
    };
    if (requestedVersion && versionEntry && requestedVersion !== vc.default) {
      mdRaw = await gitReadFile(versionEntry.branch, `docs/${slug}.md`, cwd);
      if (mdRaw != null) {
        const readFromVersion = async (absPath) => {
          const relFromDocs = path.relative(path.join(cwd, 'docs'), absPath).replace(/\\/g, '/');
          const gitPath = `docs/${relFromDocs}`;
          const fromGit = await gitReadFile(versionEntry.branch, gitPath, cwd);
          if (fromGit == null) throw new Error(`Include target not found in ${versionEntry.branch}: ${gitPath}`);
          return fromGit;
        };
        const existsFromVersion = async (absPath) => {
          const relFromDocs = path.relative(path.join(cwd, 'docs'), absPath).replace(/\\/g, '/');
          const gitPath = `docs/${relFromDocs}`;
          const fromGit = await gitReadFile(versionEntry.branch, gitPath, cwd);
          return fromGit != null;
        };
        parseOpts = {
          ...parseOpts,
          pagePath: `docs/${slug}.md@${versionEntry.branch}`,
          readFile: readFromVersion,
          pathExists: existsFromVersion,
          strictFsSafety: false,
        };
      }
    }
    if (mdRaw == null) {
      if (!await pathExists(mdPath)) return res.status(404).send('Not found');
      mdRaw = await fs.readFile(mdPath, 'utf8');
    }

    const { preprocessedMarkdown } = await parseDoc(mdRaw, parseOpts);
    res.setHeader('Content-Type', 'text/markdown; charset=utf-8');
    const isApiPage = slug.startsWith('api/') || /^---\n[\s\S]*?layout:\s*api[\s\S]*?\n---/.test(mdRaw);
    res.send(isApiPage && specData && buildApiPageMarkdown ? buildApiPageMarkdown(preprocessedMarkdown, specData) : preprocessedMarkdown);
  });

  // API: search index
  async function handleSearchIndex(req, res) {
    const freshConfig = await loadConfig(cwd);
    const pageIds = getAllPageIds(freshConfig);
    const docsDir = path.join(cwd, 'docs');
    const index = [];

    const groupMap = {};
    const tabMap = {};
    const hiddenIds = collectHiddenIds(freshConfig.sidebar);
    for (const entry of walkPages(freshConfig)) {
      if (!(entry.id in groupMap)) {
        groupMap[entry.id] = entry.group || 'Pages';
        if (entry.tabLabel) tabMap[entry.id] = entry.tabLabel;
      }
    }

    for (const id of pageIds) {
      const mdPath = path.resolve(docsDir, `${id}.md`);
      if (!mdPath.startsWith(docsDir + path.sep)) continue;
      if (!await pathExists(mdPath)) continue;
      const raw = await fs.readFile(mdPath, 'utf8');
      const { meta } = await cachedParseDoc(mdPath, raw, {
        docsRoot: path.join(cwd, 'docs'),
        pagePath: mdPath,
        globalAttributes: getRuntimeAttributes(
          freshConfig,
          freshConfig.versions?.default || null,
          freshConfig.versions?.list?.find(v => v.version === freshConfig.versions?.default)?.branch || null,
        ),
      });
      if (meta.draft === true) continue;
      if (hiddenIds.has(id) || !isSearchableMeta(meta)) continue;
      const bodyMatch = raw.match(/^---\n[\s\S]*?\n---\n?([\s\S]*)$/);
      const body = bodyMatch ? bodyMatch[1].trim() : raw.trim();
      const doc = {
        id,
        title: meta.title || id.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase()),
        group: groupMap[id] || 'Pages',
        desc: meta.description || meta.desc || '',
        body,
      };
      if (tabMap[id]) doc.tab = tabMap[id];
      index.push(doc);
    }

    res.json(index);
  }
  app.get('/api/search-index', handleSearchIndex);
  app.get('/api/search-index/:version', handleSearchIndex);

  // Serve local Lit vendor bundles (no CDN requests)
  app.use('/vendor', express.static(path.join(__dirname, 'vendor')));
  // KaTeX CSS + fonts (math is rendered at build/parse time; only the stylesheet is client-side)
  app.use('/katex', express.static(katexDistDir()));

  // Serve favicon assets from src/assets/
  app.use(express.static(path.join(__dirname, 'assets')));

  // Serve custom user components
  app.use('/components', express.static(path.join(cwd, 'components')));

  // Configured logo files live at the project root (build copies them to the same relative path).
  app.use((req, res, next) => {
    const rel = req.path.replace(/^\//, '');
    if (!logoFiles(config).some((f) => f.replace(/^\/+/, '') === rel)) return next();
    const resolved = path.resolve(cwd, rel);
    if (!resolved.startsWith(cwd + path.sep) || !existsSync(resolved)) return next();
    res.sendFile(resolved);
  });

  // Serve docs/ static assets (images etc.) with path traversal protection
  const docsStaticDir = path.join(cwd, 'docs');
  app.use((req, res, next) => {
    const ext = path.extname(req.path).toLowerCase();
    if (!['.png', '.jpg', '.jpeg', '.gif', '.svg', '.webp', '.ico', '.mp4', '.webm'].includes(ext)) return next();
    const resolved = path.resolve(docsStaticDir, req.path.replace(/^\//, ''));
    if (!resolved.startsWith(docsStaticDir + path.sep)) return next();
    if (!existsSync(resolved)) return next();
    res.sendFile(resolved);
  });

  // Catch-all: serve the app shell (or raw Markdown via Accept header)
  app.get('/{*path}', async (req, res) => {
    const vc = getVersionConfig(config);

    // Content negotiation: serve raw Markdown when Accept: text/markdown
    if (req.accepts('text/markdown') && !req.accepts('text/html')) {
      let slug = req.path.replace(/^\//, '').replace(/\/$/, '') || 'index';
      let requestedVersion = null;
      if (vc) {
        for (const v of vc.list) {
          if (slug.startsWith(v.version + '/')) {
            requestedVersion = v.version;
            slug = slug.slice(v.version.length + 1);
            break;
          }
        }
      }
      const docsDir = path.join(cwd, 'docs');
      const mdPath = path.resolve(docsDir, `${slug}.md`);
      if (mdPath.startsWith(docsDir + path.sep)) {
        const versionEntry = requestedVersion
          ? vc?.list?.find(v => v.version === requestedVersion)
          : vc?.list?.find(v => v.version === vc?.default);
        let mdRaw = null;
        let parseOpts = {
          docsRoot: path.join(cwd, 'docs'),
          pagePath: mdPath,
          globalAttributes: getRuntimeAttributes(config, requestedVersion || vc?.default || null, versionEntry?.branch || null),
        };
        if (requestedVersion && versionEntry && requestedVersion !== vc.default) {
          mdRaw = await gitReadFile(versionEntry.branch, `docs/${slug}.md`, cwd);
          if (mdRaw != null) {
            const readFromVersion = async (absPath) => {
              const relFromDocs = path.relative(path.join(cwd, 'docs'), absPath).replace(/\\/g, '/');
              const gitPath = `docs/${relFromDocs}`;
              const fromGit = await gitReadFile(versionEntry.branch, gitPath, cwd);
              if (fromGit == null) throw new Error(`Include target not found in ${versionEntry.branch}: ${gitPath}`);
              return fromGit;
            };
            const existsFromVersion = async (absPath) => {
              const relFromDocs = path.relative(path.join(cwd, 'docs'), absPath).replace(/\\/g, '/');
              const gitPath = `docs/${relFromDocs}`;
              const fromGit = await gitReadFile(versionEntry.branch, gitPath, cwd);
              return fromGit != null;
            };
            parseOpts = {
              ...parseOpts,
              pagePath: `docs/${slug}.md@${versionEntry.branch}`,
              readFile: readFromVersion,
              pathExists: existsFromVersion,
              strictFsSafety: false,
            };
          }
        }
        if (mdRaw == null) {
          if (!await pathExists(mdPath)) return res.status(404).send('Not found');
          mdRaw = await fs.readFile(mdPath, 'utf8');
        }
        const { preprocessedMarkdown } = await parseDoc(mdRaw, parseOpts);
        const isApi = slug.startsWith('api/') || /^---\n[\s\S]*?layout:\s*api[\s\S]*?\n---/.test(mdRaw);
        res.setHeader('Content-Type', 'text/markdown; charset=utf-8');
        return res.send(isApi && specData && buildApiPageMarkdown ? buildApiPageMarkdown(preprocessedMarkdown, specData) : preprocessedMarkdown);
      }
      return res.status(404).send('Not found');
    }

    let shellConfig = config;
    let currentVersion = null;

    if (vc) {
      currentVersion = vc.default;
      const pathMatch = req.path.match(/^\/([^/]+)\//);
      if (pathMatch) {
        const requestedVersion = pathMatch[1];
        const entry = vc.list.find(v => v.version === requestedVersion);
        if (entry) {
          currentVersion = entry.version;
          if (entry.version !== vc.default) {
            const versionNav = await getVersionNavigation(entry.branch, cwd);
            if (versionNav.sidebar.length) shellConfig = { ...config, sidebar: versionNav.sidebar, tabs: versionNav.tabs || undefined };
          }
        }
      }
    }

    res.setHeader('Content-Type', 'text/html; charset=utf-8');
    res.send(await renderShell({ config: shellConfig, siteTheme, mode: 'dev', port, versionConfig: vc, currentVersion, specData, apiMeta, titleMap, navMeta }));
  });

  const basePath = normalizeBasePath(config.basePath);
  server.listen(port, () => {
    const url = basePath ? `http://localhost:${port}${basePath}` : `http://localhost:${port}`;
    console.log(`  ${pc.green('✓')} Ready at ${pc.cyan(url)}`);
    if (basePath) console.log(`  ${pc.dim(`basePath: ${basePath}`)}`);
    console.log(`  ${pc.dim('Watching docs/ for changes...')}\n`);
  });
}
