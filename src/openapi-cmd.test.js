import { describe, it, expect } from 'vitest';
import fs from 'fs-extra';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';
import { openapiScaffold } from './openapi-cmd.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SPEC = path.join(__dirname, 'test-fixtures', 'petstore.yaml');

async function scaffold(sidebar) {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'docslit-oa-'));
  await fs.ensureDir(path.join(dir, 'docs'));
  await fs.writeFile(path.join(dir, 'docs', 'guide.md'), '# Guide\n');
  const cfg = { name: 'T' };
  if (sidebar !== undefined) cfg.sidebar = sidebar;
  await fs.writeJson(path.join(dir, 'docslit.json'), cfg);
  const cwd = process.cwd();
  const log = console.log;
  process.chdir(dir);
  console.log = () => {};
  try { await openapiScaffold([SPEC]); } finally { process.chdir(cwd); console.log = log; }
  return fs.readJson(path.join(dir, 'docslit.json'));
}

describe('openapi scaffold sidebar handling', () => {
  it('leaves "sidebar": "auto" untouched but sets openapi', async () => {
    const c = await scaffold('auto');
    expect(c.sidebar).toBe('auto');
    expect(c.openapi).toBeTruthy();
  });
  it('keeps autogenerate groups and does not add API groups when api/ is autogenerated', async () => {
    const sb = [{ group: 'All', autogenerate: { directory: '.', collapsed: true } }];
    const c = await scaffold(sb);
    expect(c.sidebar).toEqual(sb);
  });
  it('preserves an unrelated autogenerate group and appends API pages', async () => {
    const c = await scaffold([{ group: 'Guides', autogenerate: 'guides' }]);
    expect(c.sidebar[0]).toEqual({ group: 'Guides', autogenerate: 'guides' });
    expect(c.sidebar.length).toBeGreaterThan(1);
  });
});
