import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import fs from 'fs-extra';
import os from 'os';
import path from 'path';
import { expandSidebar, expandAllSidebars, hasAutogenerate, isAutogeneratedPage, createFileListSource, expandSidebarValue } from './auto-sidebar.js';

let root, docs;
const write = async (rel, content = '') => {
  const f = path.join(docs, rel);
  await fs.ensureDir(path.dirname(f));
  await fs.writeFile(f, content);
};
const fm = (obj) => `---\n${Object.entries(obj).map(([k, v]) => `${k}: ${v}`).join('\n')}\n---\n# x\n`;

beforeEach(async () => {
  root = await fs.mkdtemp(path.join(os.tmpdir(), 'docslit-autosb-'));
  docs = path.join(root, 'docs');
  await fs.ensureDir(docs);
});
afterEach(() => fs.remove(root));

describe('hasAutogenerate', () => {
  it('detects auto, groups and nested groups', () => {
    expect(hasAutogenerate('auto')).toBe(true);
    expect(hasAutogenerate([{ group: 'A', pages: ['a'] }])).toBe(false);
    expect(hasAutogenerate([{ group: 'A', autogenerate: 'a' }])).toBe(true);
    expect(hasAutogenerate([{ group: 'A', pages: [{ group: 'B', autogenerate: 'b' }] }])).toBe(true);
    expect(hasAutogenerate(undefined)).toBe(false);
  });
});

describe('expandSidebar: autogenerate group', () => {
  it('orders by sidebar_position, then index/intro/overview, then alphabetical', async () => {
    await write('guides/zeta.md', fm({ title: 'Z' }));
    await write('guides/alpha.md', fm({ title: 'A' }));
    await write('guides/overview.md', fm({ title: 'O' }));
    await write('guides/index.md', fm({ title: 'I' }));
    await write('guides/last.md', fm({ sidebar_position: 1 }));
    await write('guides/first.md', fm({ sidebar_position: 0 }));
    const out = await expandSidebar({ sidebar: [{ group: 'Guides', autogenerate: 'guides' }] }, docs);
    expect(out.sidebar).toEqual([{
      group: 'Guides',
      pages: ['guides/first', 'guides/last', 'guides/index', 'guides/overview', 'guides/alpha', 'guides/zeta'],
    }]);
  });

  it('builds nested subgroups with _category.json labels and positions', async () => {
    await write('guides/intro.md', fm({ title: 'Intro' }));
    await write('guides/advanced-topics/deep.md');
    await write('guides/advanced-topics/_category.json', JSON.stringify({ label: 'Power Users', position: 0 }));
    await write('guides/getting-started/a.md');
    const out = await expandSidebar({ sidebar: [{ group: 'Guides', autogenerate: { directory: 'guides', collapsed: true } }] }, docs);
    expect(out.sidebar[0].collapsed).toBe(true);
    expect(out.sidebar[0].pages).toEqual([
      { group: 'Power Users', collapsed: true, pages: ['guides/advanced-topics/deep'] },
      'guides/intro',
      { group: 'Getting Started', collapsed: true, pages: ['guides/getting-started/a'] },
    ]);
  });

  it('skips _ files/dirs, sidebar:false, non-md, and empty directories', async () => {
    await write('g/ok.md');
    await write('g/_hidden.md');
    await write('g/_reusables/x.md');
    await write('g/off.md', fm({ sidebar: false }));
    await write('g/notes.txt', 'x');
    await write('g/empty/readme.txt', 'x');
    const out = await expandSidebar({ sidebar: [{ group: 'G', autogenerate: 'g' }] }, docs);
    expect(out.sidebar[0].pages).toEqual(['g/ok']);
  });

  it('keeps explicit pages first and does not duplicate them', async () => {
    await write('g/a.md');
    await write('g/b.md');
    const out = await expandSidebar({ sidebar: [
      { group: 'G', pages: ['g/b'], autogenerate: 'g' },
      { group: 'Other', pages: ['g/a'] },
    ] }, docs);
    expect(out.sidebar[0].pages).toEqual(['g/b']);
    expect(out.sidebar[1].pages).toEqual(['g/a']);
  });

  it('supports autogenerate inside a nested subgroup', async () => {
    await write('api/x.md');
    const out = await expandSidebar({ sidebar: [{ group: 'Ref', pages: ['intro', { group: 'API', autogenerate: 'api' }] }] }, docs);
    expect(out.sidebar[0].pages).toEqual(['intro', { group: 'API', pages: ['api/x'] }]);
  });

  it('warns on missing and traversing directories without throwing', async () => {
    const warnings = [];
    const out = await expandSidebar({ sidebar: [
      { group: 'A', autogenerate: 'nope' },
      { group: 'B', autogenerate: '../outside' },
    ] }, docs, { warn: (m) => warnings.push(m) });
    expect(out.sidebar.map((g) => g.pages)).toEqual([[], []]);
    expect(warnings).toHaveLength(2);
  });

  it('does not mutate the input and returns same config when nothing to expand', async () => {
    const cfg = { sidebar: [{ group: 'A', pages: ['a'] }] };
    expect(await expandSidebar(cfg, docs)).toBe(cfg);
    const auto = { sidebar: [{ group: 'G', autogenerate: 'g' }] };
    await write('g/a.md');
    await expandSidebar(auto, docs);
    expect(auto.sidebar[0].autogenerate).toBe('g');
  });
});

describe('expandSidebar: "auto"', () => {
  it('creates a root group named after the site plus one group per top-level folder', async () => {
    await write('introduction.md');
    await write('quickstart.md');
    await write('guides/b.md');
    await write('guides/sub/c.md');
    await write('reference/_category.json', JSON.stringify({ label: 'API Reference', position: -1 }));
    await write('reference/r.md');
    await write('_reusables/skip.md');
    const out = await expandSidebar({ name: 'Acme', sidebar: 'auto' }, docs);
    expect(out.sidebar).toEqual([
      { group: 'Acme', pages: ['introduction', 'quickstart'] },
      { group: 'API Reference', pages: ['reference/r'] },
      { group: 'Guides', pages: ['guides/b', { group: 'Sub', pages: ['guides/sub/c'] }] },
    ]);
  });

  it('falls back to "Docs" and omits an empty root group', async () => {
    await write('a/x.md');
    expect((await expandSidebar({ sidebar: 'auto' }, docs)).sidebar).toEqual([{ group: 'A', pages: ['a/x'] }]);
    await write('top.md');
    expect((await expandSidebar({ sidebar: 'auto' }, docs)).sidebar[0].group).toBe('Docs');
  });

  it('ignores invalid _category.json', async () => {
    await write('a/x.md');
    await write('a/_category.json', '{nope');
    const warnings = [];
    const out = await expandSidebar({ sidebar: 'auto' }, docs, { warn: (m) => warnings.push(m) });
    expect(out.sidebar[0].group).toBe('A');
    expect(warnings).toHaveLength(1);
  });
});

describe('expandAllSidebars / file list source', () => {
  it('expands locale sidebars against docs.<locale>', async () => {
    await write('a.md');
    await fs.outputFile(path.join(root, 'docs.fr', 'fr-only.md'), '# x');
    const out = await expandAllSidebars({ name: 'S', sidebar: 'auto', 'sidebar.fr': 'auto', sidebars: { de: 'auto' } }, root);
    expect(out.sidebar[0].pages).toEqual(['a']);
    expect(out['sidebar.fr'][0].pages).toEqual(['fr-only']);
    expect(out.sidebars.de).toEqual([]);
  });

  it('works from a git-style file list', async () => {
    const files = { 'g/a.md': fm({ sidebar_position: 2 }), 'g/b.md': fm({ sidebar_position: 1 }), 'g/s/c.md': '' };
    const source = createFileListSource(Object.keys(files), async (p) => files[p] ?? null);
    const out = await expandSidebarValue([{ group: 'G', autogenerate: 'g' }], source);
    expect(out[0].pages).toEqual(['g/b', 'g/a', { group: 'S', pages: ['g/s/c'] }]);
  });
});

describe('isAutogeneratedPage', () => {
  it('matches pages under autogenerate dirs', () => {
    const sb = [{ group: 'G', autogenerate: 'guides' }, { group: 'X', pages: ['x'] }];
    expect(isAutogeneratedPage(sb, 'guides/a')).toBe(true);
    expect(isAutogeneratedPage(sb, 'other/a')).toBe(false);
    expect(isAutogeneratedPage('auto', 'anything')).toBe(true);
  });
});
