const GLOBAL_OPTIONS = [
  ['--help, -h', 'Show help (docslit <command> --help for one command)'],
  ['--version, -v', 'Print the version'],
];

const ENVIRONMENT = [
  ['DOCSLIT_TOKEN', 'API token for publish/projects/rollback/delete in CI (no login step needed)'],
  ['DOCSLIT_API_URL', 'Override the DocsLit Cloud API base URL'],
];

export function commandNames() {
  return COMMANDS.map((c) => c.name);
}

export function getCommandHelpEntry(name) {
  return COMMANDS.find((c) => c.name === name) || null;
}

function wrap(text, width, indent) {
  const words = String(text).split(/\s+/);
  const lines = [];
  let line = '';
  for (const w of words) {
    if (line && (line + ' ' + w).length > width) { lines.push(line); line = w; } else line = line ? `${line} ${w}` : w;
  }
  if (line) lines.push(line);
  return lines.map((l, i) => (i === 0 ? l : indent + l)).join('\n');
}

function optionRows(options, indent = '    ', col = 30) {
  return options.map(([flag, desc]) => {
    const pad = flag.length >= col - 1 ? `${flag}\n${indent}${' '.repeat(col)}` : flag.padEnd(col);
    return `${indent}${pad}${wrap(desc, 96 - indent.length - col, indent + ' '.repeat(col))}`;
  }).join('\n');
}

/** `docslit --help` */
export function renderMainHelp(version) {
  const out = [];
  out.push('', `  ${pc.bold('docslit')} v${version}`, '');
  out.push('  Usage:');
  out.push('    docslit <command> [options]');
  out.push('    docslit <command> --help        Show one command\'s usage and options');
  out.push('');
  for (const group of GROUPS) {
    out.push(`  ${pc.bold(group)}`);
    for (const c of COMMANDS.filter((x) => x.group === group)) {
      out.push(`    ${`docslit ${c.name}`.padEnd(20)}${wrap(c.summary.split(/(?<=\.)\s/)[0], 66, ' '.repeat(24))}`);
    }
    out.push('');
  }
  out.push(`  ${pc.bold('Options by command')}`);
  for (const c of COMMANDS) {
    if (!c.options.length) continue;
    out.push('', `  ${pc.cyan(c.usage[0])}`);
    out.push(optionRows(c.options));
  }
  out.push('', `  ${pc.bold('Global options')}`, optionRows(GLOBAL_OPTIONS));
  out.push('', `  ${pc.bold('Environment')}`, optionRows(ENVIRONMENT));
  out.push('');
  return out.join('\n');
}

/** `docslit <command> --help`; null for an unknown command. */
export function renderCommandHelp(name) {
  const c = getCommandHelpEntry(name);
  if (!c) return null;
  const out = ['', `  ${pc.bold(`docslit ${c.name}`)} - ${wrap(c.summary, 80, '    ')}`, '', '  Usage:'];
  for (const u of c.usage) out.push(`    ${u}`);
  if (c.options.length) out.push('', '  Options:', optionRows(c.options));
  if (c.notes) out.push('', `  ${c.notes}`);
  if (c.examples?.length) {
    out.push('', '  Examples:');
    for (const e of c.examples) out.push(`    ${e}`);
  }
  if (c.group === 'DocsLit Cloud' && !['login', 'logout'].includes(c.name)) out.push('', `  Credentials: DOCSLIT_TOKEN (env) or the stored login (docslit login).`);
  out.push('');
  return out.join('\n');
}
