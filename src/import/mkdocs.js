// ─── per-page hooks (called from core.js) ─────────────────────────────────────
const STATUS = { new: 'new', deprecated: 'deprecated', beta: 'beta', experimental: 'preview' };

/** MkDocs/Material frontmatter -> keys convertFrontmatter understands. */
export function mkdocsFrontmatter(fm, report = () => {}) {
  const d = { ...(fm || {}) };
  const out = {};
  for (const k of ['title', 'description']) if (d[k] !== undefined) { out[k] = d[k]; delete d[k]; }
  if (Array.isArray(d.hide)) {
    const h = d.hide.map(String);
    if (h.includes('toc')) out.hide_toc = true;
    if (h.includes('footer')) out.hide_nav = true;
    if (h.includes('feedback')) out.hide_feedback = true;
    delete d.hide;
  }
  if (d.status !== undefined) { const s = STATUS[String(d.status)]; if (s) out.availability = s; delete d.status; }
  if (d.search && typeof d.search === 'object') { if (d.search.exclude === true) out.searchable = false; delete d.search; }
  if (typeof d.icon === 'string') {
    const name = mapFrontmatterIcon(d.icon);
    if (name) out.icon = name;
    delete d.icon;
  }
  if (d.date !== undefined) { const v = d.date && typeof d.date === 'object' && !(d.date instanceof Date) ? (d.date.updated || d.date.created) : d.date; if (v) out.updated = v instanceof Date ? v.toISOString().slice(0, 10) : String(v).slice(0, 10); delete d.date; }
  if (d.draft !== undefined) { out.draft = d.draft; delete d.draft; }
  void report;
  return { ...out, ...d };
}

/**
 * Resolve a pymdownx.snippets spec ("path", "path:3:10", "path:section") for a page.
 * Code mode copies the file into the project's snippets/ folder for `file=` imports.
 */
export function readMkdocsSnippet(imp, spec, fromRel, { code = false, relative = false } = {}) {
  const mk = imp.mkdocs;
  let file = String(spec).trim();
  let lines = null;
  let section = null;
  const m = /^(.*?)(?::(-?\d+)(?::(-?\d+))?|:([\w-]+))?$/.exec(file);
  if (m && m[1] && (m[2] || m[4]) && !/^[a-z]:$/i.test(m[1])) { file = m[1]; if (m[4]) section = m[4]; else lines = [Number(m[2]), m[3] !== undefined ? Number(m[3]) : null]; }
  if (/^https?:\/\//.test(file)) return { error: 'remote snippets are not downloaded' };
  const fromAbsDir = path.dirname(path.join(mk.docsDir, fromRel));
  const bases = relative ? [fromAbsDir, ...mk.snippetBases, mk.configDir, mk.docsDir] : [...mk.snippetBases, mk.docsDir, fromAbsDir, mk.configDir];
  let abs = null;
  for (const b of bases) { const c = path.resolve(b, file); try { if (fs.statSync(c).isFile()) { abs = c; break; } } catch { /* next */ } }
  if (!abs) return { error: `file not found (looked in ${bases.map((b) => posix(path.relative(mk.configDir, b)) || '.').filter((v, i, a) => a.indexOf(v) === i).join(', ')})` };
  if (code && !section) {
    // keep the folder structure (files outside the config dir lose only their leading ../)
    const rel = posix(path.relative(mk.configDir, abs));
    const codeFile = 'snippets/' + rel.replace(/^(\.\.\/)+/, '');
    imp.outFiles.set(codeFile, fs.readFileSync(abs));
    let range = null;
    if (lines) {
      const total = fs.readFileSync(abs, 'utf8').split('\n').length;
      const a = lines[0] < 0 ? total + lines[0] + 1 : Math.max(1, lines[0]);
      const b = lines[1] == null ? total : lines[1] < 0 ? total + lines[1] + 1 : lines[1];
      range = `${a}-${b}`;
    }
    return { codeFile, lines: range };
  }
  let text = fs.readFileSync(abs, 'utf8');
  if (section) {
    const start = new RegExp(`-{1,}8<-{1,}\\s*\\[\\s*start\\s*:\\s*${section}\\s*\\]`);
    const end = new RegExp(`-{1,}8<-{1,}\\s*\\[\\s*end\\s*:\\s*${section}\\s*\\]`);
    const ls = text.split('\n');
    const s = ls.findIndex((l) => start.test(l));
    const e = ls.findIndex((l, i) => i > s && end.test(l));
    if (s === -1) return { error: `section "${section}" not found in ${path.basename(abs)}` };
    text = ls.slice(s + 1, e === -1 ? ls.length : e).join('\n');
  } else if (lines) {
    const ls = text.split('\n');
    const a = lines[0] < 0 ? ls.length + lines[0] : Math.max(0, lines[0] - 1);
    const b = lines[1] == null ? ls.length : lines[1] < 0 ? ls.length + lines[1] + 1 : lines[1];
    text = ls.slice(a, b).join('\n');
  }
  return { text };
}
