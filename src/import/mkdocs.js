/**
 * Map the loaded config into docslit.json and register pages/assets on the importer.
 * imp.sourceDir is the docs_dir. Returns the docslit.json object.
 */
export async function convertMkdocs(imp, loaded, opts = {}) {
  const cfg = loaded.cfg || {};
  const file = loaded.file;
  const rep = (sev, code, msg, extra = {}) => imp.report(sev, code, msg, { file, ...extra });
  const mapped = (from, to) => imp.reporter.mapKey(from, to);
  const unmapped = (from, note) => imp.reporter.unmapKey(from, note);
  const out = {};
  const docsDir = imp.sourceDir;
  const theme = typeof cfg.theme === 'string' ? { name: cfg.theme } : (cfg.theme || {});
  const features = new Set((theme.features || []).map(String));
  const exts = namedEntries(cfg.markdown_extensions);
  const plugins = namedEntries(cfg.plugins, { nestedPrefixes: [] });
  if (!cfg.plugins) plugins.set('search', {});
  const extNames = new Set([...exts.keys()].map((k) => k.replace(/^markdown\.extensions\./, '')));
  const useDirUrls = cfg.use_directory_urls !== false;

  // shared state for core.js page hooks
  const macrosOn = plugins.has('macros') || [...exts.keys()].some((k) => /(^|\.)macros$/.test(k));
  const extra = cfg.extra && typeof cfg.extra === 'object' ? cfg.extra : {};
  const varName = (n) => String(n).replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^A-Za-z0-9]+/g, '_').toUpperCase();
  const snipOpts = exts.get('pymdownx.snippets') || {};
  const snippetBases = [].concat(snipOpts.base_path ?? ['.']).map((b) => path.resolve(loaded.dir, String(b)));
  imp.mkdocs = {
    configDir: loaded.dir,
    docsDir,
    useDirUrls,
    exts: extNames,
    tabsSync: features.has('content.tabs.link'),
    snippetBases,
    snippetSources: new Set(),
    macros: {
      enabled: macrosOn,
      resolve(name) {
        const key = name.replace(/^config\.extra\./, '').replace(/^extra\./, '');
        if (name === 'config.site_name' || name === 'site_name') { imp.attributes.SITE_NAME = String(cfg.site_name || ''); return 'SITE_NAME'; }
        const v = key.split('.').reduce((o, k) => (o && typeof o === 'object' ? o[k] : undefined), extra);
        if (v === undefined || (typeof v === 'object' && v !== null)) return null;
        const n = varName(key);
        imp.attributes[n] = v;
        return n;
      },
    },
  };

  // ── site identity ──
  out.name = String(cfg.site_name || path.basename(loaded.dir));
  mapped('site_name', 'name');
  if (cfg.site_description) { out.description = String(cfg.site_description).trim(); mapped('site_description', 'description'); }
  if (cfg.site_url) {
    try {
      const u = new URL(String(cfg.site_url));
      out.url = `${u.protocol}//${u.host}`;
      const bp = u.pathname.replace(/\/+$/, '');
      if (bp) out.basePath = bp;
      mapped('site_url', bp ? 'url + basePath' : 'url');
    } catch { unmapped('site_url', 'not a valid URL'); }
  }
  if (cfg.repo_url) {
    const repo = String(cfg.repo_url);
    out.navbar = { links: [/github\.com/.test(repo) ? { type: 'github', href: repo } : { label: cfg.repo_name || 'Repository', href: repo }] };
    mapped('repo_url', 'navbar.links');
  }
  if (cfg.edit_uri !== undefined) unmapped('edit_uri', 'pages now live in this project\'s docs/ folder; DocsLit detects the edit link from the git remote (set "editUrl" to override)');
  if (cfg.copyright) { out.footer = { ...(out.footer || {}), copyright: String(cfg.copyright).replace(/<[^>]+>/g, '').replace(/&copy;/g, '©').replace(/&amp;/g, '&').trim() }; mapped('copyright', 'footer.copyright'); }
  const socials = {};
  for (const s of Array.isArray(extra.social) ? extra.social : []) {
    const icon = String(s.icon || '');
    const name = /(github|gitlab|x-twitter|twitter|discord|slack|linkedin|youtube|facebook|instagram|reddit|bluesky|mastodon|telegram|medium|python|docker)/.exec(icon)?.[1];
    if (name && s.link) socials[name === 'twitter' ? 'x' : name === 'x-twitter' ? 'x' : name] = String(s.link);
  }
  if (Object.keys(socials).length) { out.footer = { ...(out.footer || {}), socials }; mapped('extra.social', 'footer.socials'); }

  // ── analytics ──
  const an = extra.analytics;
  if (an && typeof an === 'object') {
    if (an.provider === 'google' && an.property) { out.analytics = { provider: 'ga4', measurementId: String(an.property) }; mapped('extra.analytics', 'analytics (ga4)'); }
    else unmapped('extra.analytics', `provider "${an.provider}" is not mapped; set "analytics" or "head" in docslit.json`);
    if (an.feedback) { out.feedback = true; mapped('extra.analytics.feedback', 'feedback'); rep('info', 'mkdocs-feedback', 'Material page feedback was enabled; DocsLit\'s feedback widget is turned on. It forwards answers to your endpoint, not to Google Analytics.', { fix: 'Configure "feedback" in docslit.json.' }); }
  }
  if (extra.version?.provider === 'mike' || plugins.has('mike')) {
    rep('warning', 'mkdocs-versioning', 'Versioned docs (mike) were not imported: only the current branch was converted.', { fix: 'Use DocsLit branch-based versions: keep one git branch per version and list them under "versions" in docslit.json.' });
    unmapped('extra.version (mike)', 'use "versions" in docslit.json');
  }
  if (extra.announcement || theme.announcement) unmapped('announcement', 'set "announcement" in docslit.json');

  // ── theme ──
  const brand = { light: {}, dark: {}, colors: {} };
  let appearance;
  const palettes = Array.isArray(theme.palette) ? theme.palette : theme.palette ? [theme.palette] : [];
  if (palettes.length) {
    const p = palettes.find((x) => x && x.primary) || palettes[0] || {};
    const hex = MATERIAL_COLORS[String(p.primary || '').toLowerCase().replace(/\s+/g, '-')];
    if (hex && !['white', 'black'].includes(String(p.primary).toLowerCase())) { brand.colors.primary = hex; mapped('theme.palette.primary', 'theme.colors.primary (dark-mode shade derived for contrast)'); }
    const schemes = palettes.map((x) => x && x.scheme).filter(Boolean);
    if (schemes.length === 1) appearance = schemes[0] === 'slate' ? 'dark' : 'light';
    else if (schemes.length > 1) appearance = 'system';
  }
  const fonts = {};
  if (theme.font && typeof theme.font === 'object') {
    // Roboto / Roboto Mono are Material's defaults, not a brand choice: keep the DocsLit theme fonts
    if (theme.font.text && !/^Roboto$/i.test(String(theme.font.text))) fonts.sans = String(theme.font.text);
    if (theme.font.code && !/^Roboto Mono$/i.test(String(theme.font.code))) fonts.mono = String(theme.font.code);
    if (Object.keys(fonts).length) { mapped('theme.font', 'theme.fonts'); brand.dark.text3 = '#8f8f8f'; }
  }
  const t = buildThemeConfig({ vendor: 'mkdocs', brand, fonts, appearance, themeOpt: opts.themeOpt, report: (s, c, m, x) => imp.report(s, c, m, x) });
  if (t !== undefined) out.theme = t;
  if (theme.logo) { out.logo = imp.configAsset(String(theme.logo), 'theme.logo'); mapped('theme.logo', 'logo'); }
  else if (theme.icon?.logo) unmapped('theme.icon.logo', `icon "${theme.icon.logo}": export it as an SVG file and set "logo"`);
  if (theme.favicon) { out.favicon = imp.configAsset(String(theme.favicon), 'theme.favicon'); mapped('theme.favicon', 'favicon'); }
  if (theme.name && !['material', 'mkdocs', 'readthedocs'].includes(String(theme.name))) rep('info', 'mkdocs-theme', `Theme "${theme.name}" was replaced by a DocsLit theme.`, { fix: 'Pick a look with `docslit theme use <name>`.' });
  const kept = [...features].filter((f) => FEATURE_NOTES[f]).map((f) => `${f} → ${FEATURE_NOTES[f]}`);
  if (kept.length) mapped('theme.features', kept.join('; '));
  const notKept = [...features].filter((f) => !FEATURE_NOTES[f]);
  if (notKept.length) unmapped('theme.features', `${notKept.join(', ')} (Material UI behaviours with no setting in DocsLit)`);
  if (theme.custom_dir) {
    const overridesAbs = path.resolve(loaded.dir, String(theme.custom_dir));
    const files = (await fs.pathExists(overridesAbs)) ? (await walkFiles(overridesAbs)).filter((f) => /\.html$/.test(f)) : [];
    rep('warning', 'mkdocs-theme-overrides', `Theme overrides in ${theme.custom_dir}/ (${files.length} Jinja template${files.length === 1 ? '' : 's'}${files.length ? ': ' + files.slice(0, 5).join(', ') + (files.length > 5 ? ', …' : '') : ''}) cannot run in DocsLit.`, {
      action: 'Not copied.', fix: 'Use docslit.json instead: "announcement" for the banner, "head" for extra tags, "footer" for footer links, "css" for styles, or a custom component for anything richer.' });
    unmapped('theme.custom_dir', 'Jinja template overrides are not supported');
  }

  // ── extra_css / extra_javascript ──
  const head = [];
  const extraCss = [];
  for (const c of [].concat(cfg.extra_css || [])) {
    const p = typeof c === 'string' ? c : c?.path;
    if (!p) continue;
    if (/^(https?:)?\/\//.test(p)) { head.push(`<link rel="stylesheet" href="${p}">`); continue; }
    const abs = path.join(docsDir, p);
    if (!(await fs.pathExists(abs))) { rep('warning', 'mkdocs-extra-css-missing', `extra_css "${p}" was not found in ${posix(path.relative(loaded.dir, docsDir)) || '.'}/.`, { fix: 'Add the stylesheet to custom.css by hand.' }); continue; }
    const dir = path.posix.dirname(p);
    const css = (await fs.readFile(abs, 'utf8')).replace(/url\(\s*(['"]?)(?!data:|https?:|\/|#)([^'")]+)\1\s*\)/g, (m, q, u) => `url(${q}/${path.posix.normalize(path.posix.join(dir === '.' ? '' : dir, u))}${q})`);
    extraCss.push(`/* ${p} */\n${css}`);
  }
  if (extraCss.length) {
    imp.extraCss = (imp.extraCss || []).concat(extraCss);
    mapped('extra_css', 'custom.css');
    if (extraCss.some((c) => /\.md-|--md-/.test(c))) rep('warning', 'mkdocs-css-material', 'Custom CSS targets Material for MkDocs classes or variables (.md-*, --md-*), which do not exist in DocsLit.', { file: 'custom.css', action: 'Copied as-is.', fix: 'Rewrite those rules against DocsLit theme tokens (see `docslit theme`), or delete them.' });
  }
  const jsSkipped = [];
  for (const j of [].concat(cfg.extra_javascript || [])) {
    const p = typeof j === 'string' ? j : j?.path;
    if (!p) continue;
    if (/mathjax|katex|polyfill\.io|tablesort|arithmatex/i.test(p)) { jsSkipped.push(p); continue; }
    const isUrl = /^(https?:)?\/\//.test(p);
    const type = typeof j === 'object' && j.type ? ` type="${j.type}"` : '';
    const mode = typeof j === 'object' && j.async ? ' async' : ' defer';
    head.push(`<script src="${isUrl ? p : '/' + p.replace(/^\/+/, '')}"${type}${mode}></script>`);
  }
  if (jsSkipped.length) rep('info', 'mkdocs-js-skipped', `Scripts not needed in DocsLit were dropped: ${jsSkipped.join(', ')} (math renders with built-in KaTeX at build time).`);
  if (head.length) { out.head = head; mapped('extra_css/extra_javascript (remote, scripts)', 'head'); if (head.some((h) => h.startsWith('<script'))) rep('warning', 'mkdocs-custom-js', 'Custom JavaScript from extra_javascript is loaded on every page, but it was written for Material\'s page structure and may not work.', { action: 'Added to "head".', fix: 'Test each script and remove the ones that only tweaked Material.' }); }

  // ── markdown extensions ──
  const SUPPORTED_EXT = new Set(['admonition', 'attr_list', 'def_list', 'footnotes', 'md_in_html', 'tables', 'toc', 'abbr', 'meta', 'sane_lists', 'smarty', 'fenced_code', 'codehilite', 'nl2br',
    'pymdownx.details', 'pymdownx.superfences', 'pymdownx.highlight', 'pymdownx.inlinehilite', 'pymdownx.tabbed', 'pymdownx.snippets', 'pymdownx.keys', 'pymdownx.mark', 'pymdownx.caret', 'pymdownx.tilde',
    'pymdownx.tasklist', 'pymdownx.emoji', 'pymdownx.arithmatex', 'pymdownx.betterem', 'pymdownx.smartsymbols', 'pymdownx.magiclink', 'pymdownx.saneheaders', 'pymdownx.escapeall',
    'pymdownx.blocks.admonition', 'pymdownx.blocks.details', 'pymdownx.blocks.tab', 'pymdownx.blocks.caption', 'pymdownx.blocks.html', 'pymdownx.blocks.definition', 'pymdownx.striphtml', 'pymdownx.extra']);
  const otherExt = [...extNames].filter((e) => !SUPPORTED_EXT.has(e));
  if (otherExt.length) rep('warning', 'mkdocs-extensions-unsupported', `Markdown extensions without a DocsLit equivalent: ${otherExt.join(', ')}. Their syntax is left as written.`, { fix: 'Search the converted pages for that syntax and rewrite it (MIGRATION.md lists what was found).' });
  if (extNames.has('pymdownx.arithmatex')) { out.math = { singleDollar: true }; mapped('pymdownx.arithmatex', 'math (KaTeX, $…$ and $$…$$)'); }

  // ── plugins: loud, never silent ──
  // Material social cards -> DocsLit generated OG images (opt-in in DocsLit)
  if (plugins.has('social') || plugins.has('material/social')) out.ogImage = true;
  for (const [name] of plugins) {
    const note = PLUGIN_NOTES[name];
    if (!note) { rep('warning', 'mkdocs-plugin-not-carried', `Plugin "${name}" has no DocsLit equivalent and was not run.`, { action: 'Ignored.', fix: 'Check what the plugin added to your pages (generated pages, injected HTML) and recreate the parts you still need.' }); unmapped(`plugins.${name}`, 'not carried over'); continue; }
    const [kind, text] = note;
    if (kind === 'mapped') mapped(`plugins.${name}`, text);
    else if (kind === 'partial') { mapped(`plugins.${name}`, `partly: ${text}`); }
    else if (kind === 'error') { rep('error', `mkdocs-plugin-${name.replace(/\W+/g, '-')}`, `Plugin "${name}": ${text}.`, { action: 'See the page-level items below.' }); unmapped(`plugins.${name}`, text); }
    else { rep('warning', `mkdocs-plugin-${name.replace(/\W+/g, '-')}`, `Plugin "${name}": ${text}.`); unmapped(`plugins.${name}`, text); }
  }

  // ── pages ──
  const all = await walkFiles(docsDir);
  const excludeFn = compileGitignore(cfg.exclude_docs || '');
  const snippetDirs = snippetBases.map((b) => posix(path.relative(docsDir, b))).filter((r) => r && !r.startsWith('..'));
  const autoAppend = new Set([].concat(snipOpts.auto_append || []).map(String));
  const dirsWithIndex = new Set(all.filter((f) => /(^|\/)index\.md$/i.test(f)).map((f) => path.posix.dirname(f)));
  const overridesRel = theme.custom_dir ? posix(path.relative(docsDir, path.resolve(loaded.dir, String(theme.custom_dir)))) : null;
  const pageFiles = [];
  for (const f of all) {
    if (overridesRel && !overridesRel.startsWith('..') && f.startsWith(overridesRel + '/')) continue;
    if (excludeFn(f)) { if (isMd(f)) rep('info', 'mkdocs-excluded', `${f} matches exclude_docs; skipped.`, { file: f }); continue; }
    if (isMd(f)) {
      if (snippetDirs.some((d) => f.startsWith(d + '/')) || autoAppend.has(f) || /(^|\/)(_snippets|\.snippets|snippets|includes|_includes|partials)\//.test(f)) { imp.mkdocs.snippetSources.add(f); continue; }
      pageFiles.push(f);
      continue;
    }
    if (/\.(py|pyc|ipynb|j2|jinja2?)$/i.test(f)) continue;
    const abs = path.join(docsDir, f);
    if (/\.(html?)$/i.test(f)) { imp.assets.set(abs, f); continue; } // static HTML pages are copied like any file
    imp.assets.set(abs, f);
  }
  if ([...all].some((f) => /\.ipynb$/i.test(f))) rep('warning', 'mkdocs-notebooks', 'Jupyter notebooks (.ipynb) were not imported.', { fix: 'Export them with `jupyter nbconvert --to markdown` and re-run the import.' });
  for (const f of pageFiles) imp.registerPage(f, mkdocsSlug(f, dirsWithIndex.has(path.posix.dirname(f))), {});
  if (imp.mkdocs.snippetSources.size) rep('info', 'mkdocs-snippet-files', `${imp.mkdocs.snippetSources.size} Markdown file(s) in snippet folders were treated as include-only and not published as pages.`);

  // ── nav ──
  const navRaw = cfg.nav;
  const listed = new Set();
  if (Array.isArray(navRaw) && navRaw.length) {
    const indexes = features.has('navigation.indexes') || plugins.has('section-index');
    const items = convertNavList(navRaw, imp, rep, listed, indexes);
    if (features.has('navigation.tabs') && items.some((it) => it.group !== undefined)) {
      out.tabs = buildTabs(items, out.name);
      mapped('nav + navigation.tabs', 'tabs');
    } else {
      out.sidebar = groupTopLevel(items, out.name);
      mapped('nav', 'sidebar');
    }
  } else {
    out.sidebar = 'auto';
    mapped('(implicit nav)', 'sidebar: "auto"');
  }
  if (listed.size) {
    // DocsLit builds the pages its sidebar lists, so pages outside the nav must still be listed.
    let unlisted = [...imp.pages].filter(([, info]) => !listed.has(info.slug)).map(([src, i]) => ({ src, slug: i.slug }));
    // blog posts (Material blog plugin): listed under the blog's group, newest first
    const blogOpts = plugins.get('blog') || plugins.get('material/blog');
    if (blogOpts) {
      const blogDir = String(blogOpts.blog_dir || 'blog').replace(/^\.?\/|\/$/g, '');
      const posts = unlisted.filter((u) => u.slug.startsWith(blogDir + '/'));
      if (posts.length) {
        const dated = posts.map((u) => ({ ...u, date: postDate(path.join(docsDir, u.src)) })).sort((a, b) => String(b.date).localeCompare(String(a.date)) || a.slug.localeCompare(b.slug));
        const target = findGroup(out.tabs ? out.tabs.flatMap((t) => t.sidebar || []) : out.sidebar, (g) => g.root === `${blogDir}/index` || (g.pages || []).some((p) => (typeof p === 'string' ? p : p.id) === `${blogDir}/index`));
        const ids = dated.map((u) => u.slug);
        if (target) target.pages.push(...ids);
        else if (out.tabs) out.tabs.push({ tab: 'Blog', sidebar: [{ group: 'Blog', pages: ids }] });
        else out.sidebar.push({ group: 'Blog', pages: ids });
        for (const u of posts) listed.add(u.slug);
        unlisted = unlisted.filter((u) => !listed.has(u.slug));
        rep('info', 'mkdocs-blog-posts', `${posts.length} blog post(s) were added to the sidebar under the blog section, newest first.`, { fix: 'Material\'s archive, category and pagination pages are not generated; the RSS feed covers pages under blog/.' });
      }
    }
    if (unlisted.length) {
      const hidden = { group: 'Not in navigation', hidden: true, pages: unlisted.map((u) => u.slug) };
      if (out.tabs) out.tabs.push({ tab: 'Other pages', hidden: true, sidebar: [hidden] }); else out.sidebar.push(hidden);
      rep('info', 'mkdocs-not-in-nav', `${unlisted.length} page(s) are not in the nav. They are built and linkable through a hidden sidebar group, but are left out of search and the sitemap: ${unlisted.slice(0, 8).map((u) => u.slug).join(', ')}${unlisted.length > 8 ? ', …' : ''}.`, { fix: 'Move them into a visible sidebar group in docslit.json if readers should find them.' });
    }
  }

  // ── redirects plugin ──
  const redirectMaps = plugins.get('redirects')?.redirect_maps;
  if (redirectMaps && typeof redirectMaps === 'object') {
    let n = 0;
    for (const [from, to] of Object.entries(redirectMaps)) {
      const fromSlug = mkdocsSlug(String(from), false).replace(/\/index$/, '').replace(/^index$/, '');
      let target = String(to);
      if (!/^https?:\/\//.test(target)) {
        const [p, hash] = target.split('#');
        const slug = imp.slugBySrc.get(p.replace(/\.(md|markdown)$/i, '')) ?? mkdocsSlug(p, false);
        target = '/' + slug + (hash ? '#' + hash : '');
      }
      imp.redirects['/' + fromSlug] = target;
      n++;
    }
    if (n) mapped('plugins.redirects.redirect_maps', `redirects (${n})`);
  }

  if (useDirUrls) rep('info', 'mkdocs-url-style', 'MkDocs served pages at /page/ (with a trailing slash); DocsLit serves /page. Page paths are unchanged, but whether /page/ still answers depends on your host (Vercel and Cloudflare Pages redirect it to /page).', { fix: 'After deploying, open a few old /page/ URLs. If your host returns 404 for them (GitHub Pages does), enable its trailing-slash redirect or deploy to a host that has one.' });
  if (cfg.strict) mapped('strict', 'docslit validate (run it in CI to fail on broken links)');
  return out;
}

function findGroup(groups, pred) {
  for (const g of Array.isArray(groups) ? groups : []) {
    if (!g || typeof g !== 'object' || g.group === undefined) continue;
    if (pred(g)) return g;
    const inner = findGroup(g.pages, pred);
    if (inner) return inner;
  }
  return null;
}

function postDate(abs) {
  try {
    const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(fs.readFileSync(abs, 'utf8'));
    const y = m ? yamlLoad(m[1]) || {} : {};
    const d = y.date && typeof y.date === 'object' && !(y.date instanceof Date) ? y.date.created : y.date;
    return d instanceof Date ? d.toISOString() : String(d || '');
  } catch { return ''; }
}

function convertNavList(list, imp, rep, listed, indexes) {
  const out = [];
  for (const entry of list) {
    let title = null;
    let target = entry;
    if (entry && typeof entry === 'object' && !Array.isArray(entry)) {
      const keys = Object.keys(entry);
      if (keys.length !== 1) continue;
      title = keys[0];
      target = entry[title];
    }
    if (Array.isArray(target)) {
      const pages = convertNavList(target, imp, rep, listed, indexes);
      const g = { group: title || 'Section', pages };
      if (indexes && pages.length && typeof pages[0] === 'object' && pages[0].id && /(^|\/)index$/.test(pages[0].id)) { g.root = pages[0].id; pages.shift(); }
      else if (indexes && typeof pages[0] === 'string' && /(^|\/)index$/.test(pages[0])) { g.root = pages[0]; pages.shift(); }
      out.push(g);
      continue;
    }
    if (typeof target !== 'string') continue;
    if (/^(https?:|mailto:)/i.test(target) || target.startsWith('/') || target.startsWith('#') || target.startsWith('..')) {
      out.push({ href: target, title: title || target });
      continue;
    }
    const rel = target.replace(/^\.\//, '');
    const info = imp.pages.get(rel) || imp.pages.get(rel.replace(/\/$/, '') + '/index.md');
    if (!info) { rep('warning', 'nav-page-missing', `nav entry "${target}" has no file in the docs folder.`, { action: 'Removed from the sidebar.', fix: 'Create the page or remove the entry.' }); continue; }
    listed.add(info.slug);
    out.push(title ? { id: info.slug, title: String(title) } : info.slug);
  }
  return out;
}

/** DocsLit sidebars are groups at the top level: wrap runs of loose pages into groups. */
function groupTopLevel(items, siteName) {
  const out = [];
  let run = null;
  for (const it of items) {
    if (it.group !== undefined) { run = null; out.push(it); continue; }
    if (!run) { run = { group: out.length ? null : siteName, pages: [] }; out.push(run); }
    run.pages.push(it);
  }
  // a later run of loose pages is named after its only entry, or "More"
  for (const g of out) {
    if (g.group !== null) continue;
    const only = g.pages.length === 1 ? g.pages[0] : null;
    g.group = only && typeof only === 'object' && only.title ? only.title : 'More';
  }
  return out;
}

function buildTabs(items, siteName) {
  const tabs = [];
  let loose = null;
  for (const it of items) {
    if (it.group !== undefined) {
      const inner = it.pages.length ? groupTopLevel(it.pages, it.group) : [];
      const sidebar = it.root ? [{ group: it.group, root: it.root, pages: [] }, ...inner].filter((g) => g.pages.length || g.root) : inner;
      tabs.push({ tab: it.group, sidebar: sidebar.length ? sidebar : [{ group: it.group, pages: [] }] });
      loose = null;
      continue;
    }
    if (it.href) { tabs.push({ tab: it.title, href: it.href }); continue; }
    if (!loose) { loose = { tab: tabs.length ? 'More' : 'Home', sidebar: [{ group: siteName, pages: [] }] }; tabs.push(loose); }
    loose.sidebar[0].pages.push(it);
  }
  return tabs;
}

