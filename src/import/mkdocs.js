// ─── loading ──────────────────────────────────────────────────────────────────
export async function findMkdocsConfigFile(dir) {
  for (const f of ['mkdocs.yml', 'mkdocs.yaml', 'zensical.toml']) if (await fs.pathExists(path.join(dir, f))) return f;
  return null;
}

/** Make Python-specific YAML tags loadable: !!python/name:x -> "python:x", !ENV [VAR, default] -> default, !relative -> string. */
export function sanitizeMkdocsYaml(text) {
  return String(text)
    // the value of a Python tag is irrelevant to the import: drop the tag, keep any mapping below it
    .replace(/!!python\/[\w/]+:[\w.]+/g, '')
    .replace(/!ENV\s*\[\s*([^\],]+?)\s*,\s*([^\]]*?)\s*\]/g, (m, v, d) => (d ? d : 'null'))
    .replace(/!ENV\s*\[\s*([^\],]+?)\s*\]/g, 'null')
    .replace(/!ENV\s+([A-Za-z_][\w]*)/g, 'null')
    .replace(/!relative(\s+\$\w+)?/g, (m, v) => `"${(v || '$config_dir').trim()}"`);
}

function deepMerge(base, over) {
  if (Array.isArray(base) || Array.isArray(over) || typeof base !== 'object' || typeof over !== 'object' || !base || !over) return over === undefined ? base : over;
  const out = { ...base };
  for (const [k, v] of Object.entries(over)) out[k] = k in base ? deepMerge(base[k], v) : v;
  return out;
}

/**
 * Load mkdocs.yml / zensical.toml from `dir`. INHERIT is followed.
 * @returns {{ cfg, file, dir, error? }}
 */
export async function loadMkdocsConfig(dir, { file: explicit = null } = {}) {
  let file;
  if (explicit) {
    // explicit config file (relative to `dir` or absolute): the config dir is the file's directory, as in MkDocs
    const abs0 = path.resolve(dir, explicit);
    if (!(await fs.pathExists(abs0))) return { cfg: null, file: explicit, dir, error: 'file not found' };
    dir = path.dirname(abs0);
    file = path.basename(abs0);
  } else {
    file = await findMkdocsConfigFile(dir);
  }
  if (!file) return { cfg: null, file: null, dir, error: 'no mkdocs.yml, mkdocs.yaml or zensical.toml' };
  const abs = path.join(dir, file);
  try {
    if (file.endsWith('.toml')) {
      const t = parseToml(await fs.readFile(abs, 'utf8'));
      return { cfg: t.project || t, file, dir };
    }
    const readYaml = async (p, depth = 0) => {
      const y = yamlLoad(sanitizeMkdocsYaml(await fs.readFile(p, 'utf8'))) || {};
      if (y.INHERIT && depth < 5) {
        const parentPath = path.resolve(path.dirname(p), String(y.INHERIT));
        const { INHERIT, ...rest } = y; void INHERIT;
        if (await fs.pathExists(parentPath)) return deepMerge(await readYaml(parentPath, depth + 1), rest);
        return rest;
      }
      return y;
    };
    return { cfg: await readYaml(abs), file, dir };
  } catch (e) {
    return { cfg: null, file, dir, error: String(e.message).split('\n')[0] };
  }
}

/** Plugins / markdown_extensions as a Map name -> options (list, dict and TOML-nested forms). */
export function namedEntries(v, { nestedPrefixes = ['pymdownx', 'material', 'markdown'] } = {}) {
  const out = new Map();
  if (!v) return out;
  if (Array.isArray(v)) {
    for (const it of v) {
      if (typeof it === 'string') out.set(it, {});
      else if (it && typeof it === 'object') for (const [k, o] of Object.entries(it)) out.set(k, o || {});
    }
    return out;
  }
  if (typeof v === 'object') {
    for (const [k, o] of Object.entries(v)) {
      // zensical.toml: [project.markdown_extensions.pymdownx.details] -> { pymdownx: { details: {} } }
      if (nestedPrefixes.includes(k) && o && typeof o === 'object' && !Array.isArray(o) && Object.values(o).every((x) => x && typeof x === 'object')) {
        for (const [k2, o2] of Object.entries(o)) out.set(`${k}.${k2}`, o2 || {});
      } else out.set(k, o || {});
    }
  }
  return out;
}

// ─── page discovery ───────────────────────────────────────────────────────────
async function walkFiles(dir, base = dir, out = []) {
  let entries;
  try { entries = await fs.readdir(dir, { withFileTypes: true }); } catch { return out; }
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const e of entries) {
    if (e.name.startsWith('.') && e.name !== '.well-known') continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (['node_modules', '__pycache__'].includes(e.name)) continue; await walkFiles(p, base, out); }
    else out.push(posix(path.relative(base, p)));
  }
  return out;
}

/** gitignore-style patterns from exclude_docs / not_in_nav (subset: *, **, leading /, trailing /, !negation). */
export function compileGitignore(text) {
  const rules = [];
  for (let raw of String(text || '').split('\n')) {
    raw = raw.trim();
    if (!raw || raw.startsWith('#')) continue;
    const neg = raw.startsWith('!');
    let p = neg ? raw.slice(1) : raw;
    const anchored = p.startsWith('/') || p.slice(0, -1).includes('/');
    p = p.replace(/^\//, '');
    const dirOnly = p.endsWith('/');
    p = p.replace(/\/$/, '');
    let re = p.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*\*\/?/g, '\u0000').replace(/\*/g, '[^/]*').replace(/\?/g, '[^/]').replace(/\u0000/g, '(?:.*/)?');
    re = (anchored ? '^' : '(?:^|/)') + re + (dirOnly ? '/' : '(?:$|/)');
    rules.push({ neg, re: new RegExp(re) });
  }
  return (rel) => {
    let hit = false;
    for (const r of rules) if (r.re.test(rel)) hit = !r.neg;
    return hit;
  };
}

export function mkdocsSlug(rel, hasIndexInDir) {
  const stem = rel.replace(/\.(md|markdown)$/i, '');
  if (/(^|\/)index$/i.test(stem)) return stem.replace(/index$/i, 'index');
  if (/(^|\/)README$/i.test(stem) && !hasIndexInDir) return stem.replace(/README$/i, 'index');
  return stem;
}

