import { describe, it, expect } from 'vitest';
import fs from 'fs-extra';
import path from 'path';
import { fileURLToPath } from 'url';
import { generateAuthorSkill, generateAgentsBlock, SKILLS_DIR } from './skill-gen.js';
import { listComponentTags, getComponentManifest } from './component-manifest.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
// Illustrative names used in the migrate skill to explain the PascalCase fallback.
const ILLUSTRATIVE = new Set(['wc-my-component', 'wc-api-docs-card']);

describe('skills', () => {
  it('skills/docslit-author.md is up to date (run `npm run skills`)', () => {
    const committed = fs.readFileSync(path.join(SKILLS_DIR, 'docslit-author.md'), 'utf8');
    expect(committed).toBe(generateAuthorSkill());
  });

  it('documents every component and attribute from the manifest', () => {
    const skill = generateAuthorSkill();
    for (const c of getComponentManifest()) {
      expect(skill).toContain(`#### \`${c.tag}\``);
      for (const a of c.attributes.filter((x) => x.name !== 'theme')) expect(skill).toContain(`\`${a.name}\``);
    }
  });

  it('every wc-* tag in the skill files exists in the manifest', () => {
    const tags = new Set(listComponentTags());
    for (const file of ['docslit-author.md', 'docslit-migrate.md']) {
      const text = fs.readFileSync(path.join(SKILLS_DIR, file), 'utf8');
      const mentioned = new Set(text.match(/wc-[a-z][a-z0-9]*(?:-[a-z0-9]+)*/g) || []);
      const unknown = [...mentioned].filter((t) => !tags.has(t) && !ILLUSTRATIVE.has(t));
      expect(unknown, `${file} mentions unknown tags`).toEqual([]);
    }
  });

  it('skill files have name and description frontmatter', () => {
    for (const [file, name] of [['docslit-author.md', 'docslit-author'], ['docslit-migrate.md', 'docslit-migrate']]) {
      const text = fs.readFileSync(path.join(SKILLS_DIR, file), 'utf8');
      expect(text).toMatch(new RegExp(`^---\\nname: ${name}\\ndescription: .{40,}\\n---\\n`));
    }
  });

  it('skills are published to npm', () => {
    const pkg = fs.readJsonSync(path.join(ROOT, 'package.json'));
    expect(pkg.files).toContain('skills');
    expect(pkg.scripts.skills).toBeTruthy();
  });

  it('agents block adapts to the project and only mentions real tags', () => {
    const auto = generateAgentsBlock({ sidebarMode: 'auto' });
    expect(auto).toContain('autogenerated');
    expect(generateAgentsBlock({ sidebarMode: 'explicit', groups: ['Guides'] })).toContain('"Guides"');
    expect(generateAgentsBlock({ locales: ['en', 'fr'], defaultLocale: 'en' })).toContain('docs.<locale>');
    const tags = new Set(listComponentTags());
    for (const t of auto.match(/wc-[a-z][a-z0-9-]*/g) || []) expect(tags.has(t)).toBe(true);
  });
});
