import { describe, it, expect, afterEach } from 'vitest';
import fs from 'fs-extra';
import os from 'os';
import path from 'path';
import { execFile } from 'child_process';
import { fileURLToPath } from 'url';
import { runAgentsInit, BLOCK_START, BLOCK_END } from './agents-cmd.js';

const BIN = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'bin', 'docslit.js');
const dirs = [];
afterEach(async () => { while (dirs.length) await fs.remove(dirs.pop()); });

async function proj(config = { name: 'x', sidebar: [{ group: 'Guides', pages: ['a'] }] }) {
  const d = await fs.mkdtemp(path.join(os.tmpdir(), 'docslit-agents-'));
  dirs.push(d);
  await fs.writeJson(path.join(d, 'docslit.json'), config);
  await fs.ensureDir(path.join(d, 'docs'));
  return d;
}
const run = (args, cwd) => new Promise((resolve) => execFile('node', [BIN, ...args], { cwd }, (err, stdout, stderr) => resolve({ code: err ? err.code : 0, stdout, stderr })));

describe('agents init', () => {
  it('fails outside a docs project', async () => {
    const d = await fs.mkdtemp(path.join(os.tmpdir(), 'docslit-agents-empty-'));
    dirs.push(d);
    expect((await runAgentsInit(d)).ok).toBe(false);
  });

  it('writes AGENTS.md only when no tool is detected, reflecting the real config', async () => {
    const d = await proj({ name: 'x', sidebar: 'auto', i18n: { defaultLocale: 'en', locales: ['en', 'fr'] } });
    const r = await runAgentsInit(d);
    expect(r.written).toEqual(['AGENTS.md']);
    const md = await fs.readFile(path.join(d, 'AGENTS.md'), 'utf8');
    expect(md).toContain(BLOCK_START);
    expect(md).toContain('autogenerated');
    expect(md).toContain('docs.<locale>');
  });

  it('--tool all writes every tool file, and a second run is a clean no-op', async () => {
    const d = await proj();
    const first = await runAgentsInit(d, { tools: 'all' });
    expect(first.written.sort()).toEqual([
      '.claude/skills/docslit-author/SKILL.md', '.claude/skills/docslit-migrate/SKILL.md', '.cursor/mcp.json',
      '.cursor/rules/docslit.mdc', '.github/instructions/docslit.instructions.md', '.mcp.json', '.vscode/mcp.json',
      '.windsurf/rules/docslit.md', 'AGENTS.md', 'CLAUDE.md', 'GEMINI.md',
    ].sort());
    expect(await fs.readFile(path.join(d, 'CLAUDE.md'), 'utf8')).toBe('@AGENTS.md\n');
    expect(await fs.readJson(path.join(d, '.vscode/mcp.json'))).toEqual({ servers: { docslit: { type: 'stdio', command: 'npx', args: ['-y', 'docslit', 'mcp'] } } });
    const second = await runAgentsInit(d, { tools: 'all' });
    expect(second.written).toEqual([]);
    expect(second.updated).toEqual([]);
    expect(second.skipped).toEqual([]);
    expect(second.unchanged).toHaveLength(11);
  });

  it('preserves user content in AGENTS.md and CLAUDE.md and updates only the block', async () => {
    const d = await proj();
    await fs.writeFile(path.join(d, 'AGENTS.md'), '# Mine\n\nKeep me.\n');
    await fs.writeFile(path.join(d, 'CLAUDE.md'), '# Claude notes\n');
    await runAgentsInit(d, { tools: ['claude'] });
    let md = await fs.readFile(path.join(d, 'AGENTS.md'), 'utf8');
    expect(md.startsWith('# Mine\n\nKeep me.\n')).toBe(true);
    expect(md).toContain(BLOCK_END);
    expect(await fs.readFile(path.join(d, 'CLAUDE.md'), 'utf8')).toContain('# Claude notes');
    // stale block + trailing user text gets refreshed in place
    md = md.replace(/(<!-- docslit:start -->)[\s\S]*(<!-- docslit:end -->)/, '$1\nold\n$2') + '\nAfter.\n';
    await fs.writeFile(path.join(d, 'AGENTS.md'), md);
    const r = await runAgentsInit(d, { tools: ['claude'] });
    expect(r.updated).toContain('AGENTS.md');
    const out = await fs.readFile(path.join(d, 'AGENTS.md'), 'utf8');
    expect(out).not.toContain('\nold\n');
    expect(out.startsWith('# Mine')).toBe(true);
    expect(out.endsWith('After.\n')).toBe(true);
  });

  it('merges MCP JSON without clobbering other servers and refuses to overwrite foreign files', async () => {
    const d = await proj();
    await fs.writeJson(path.join(d, '.mcp.json'), { mcpServers: { other: { command: 'x' } }, extra: 1 });
    await fs.ensureDir(path.join(d, '.windsurf/rules'));
    await fs.writeFile(path.join(d, '.windsurf/rules/docslit.md'), 'my own rule');
    const r = await runAgentsInit(d, { tools: ['claude', 'windsurf'] });
    const mcp = await fs.readJson(path.join(d, '.mcp.json'));
    expect(mcp.mcpServers.other).toEqual({ command: 'x' });
    expect(mcp.mcpServers.docslit).toEqual({ command: 'npx', args: ['-y', 'docslit', 'mcp'] });
    expect(mcp.extra).toBe(1);
    expect(r.skipped.map((s) => s.file)).toEqual(['.windsurf/rules/docslit.md']);
    expect(await fs.readFile(path.join(d, '.windsurf/rules/docslit.md'), 'utf8')).toBe('my own rule');
    const forced = await runAgentsInit(d, { tools: ['windsurf'], force: true });
    expect(forced.updated).toContain('.windsurf/rules/docslit.md');
  });

  it('skips invalid JSON instead of destroying it, and detects tools from directories', async () => {
    const d = await proj();
    await fs.writeFile(path.join(d, '.mcp.json'), '{ nope');
    await fs.ensureDir(path.join(d, '.claude'));
    const r = await runAgentsInit(d);
    expect(r.detected).toEqual(['claude']);
    expect(r.skipped.map((s) => s.file)).toEqual(['.mcp.json']);
    expect(await fs.readFile(path.join(d, '.mcp.json'), 'utf8')).toBe('{ nope');
  });

  it('rejects unknown tools', async () => {
    expect((await runAgentsInit(await proj(), { tools: ['vim'] })).ok).toBe(false);
  });

  it('CLI: --json output and `agents print`', async () => {
    const d = await proj();
    const { code, stdout } = await run(['agents', 'init', '--tool', 'cursor', '--json'], d);
    expect(code).toBe(0);
    expect(JSON.parse(stdout).written).toContain('.cursor/rules/docslit.mdc');
    const mdc = await fs.readFile(path.join(d, '.cursor/rules/docslit.mdc'), 'utf8');
    expect(mdc).toMatch(/^---\ndescription: .+\nglobs: docs\/\*\*\/\*\.md,docslit\.json\nalwaysApply: false\n---/);
    const p = await run(['agents', 'print', 'author'], os.tmpdir());
    expect(p.stdout).toMatch(/^---\nname: docslit-author/);
  });

  it('docslit init writes AGENTS.md unless --no-agents', async () => {
    const base = await fs.mkdtemp(path.join(os.tmpdir(), 'docslit-init-'));
    dirs.push(base);
    await run(['init', 'with'], base);
    await run(['init', 'without', '--no-agents'], base);
    expect(await fs.pathExists(path.join(base, 'with', 'AGENTS.md'))).toBe(true);
    expect(await fs.pathExists(path.join(base, 'without', 'AGENTS.md'))).toBe(false);
    expect(await fs.pathExists(path.join(base, 'without', 'docslit.json'))).toBe(true);
  });
});
