/**
 * docslit new <page-id> — scaffold a markdown page and optionally append to sidebar.
 * Never prompts. With --json prints { id, file, sidebarUpdated, group } to stdout.
 */
import path from 'path';
import fs from 'fs-extra';
import pc from 'picocolors';
import { isAutogeneratedPage } from './auto-sidebar.js';
import { slugify, normalizeDir } from './navigation.js';
import { stringifyFrontmatter } from './frontmatter.js';

export function toTitle(id) {
  const base = id.split('/').pop() || id;
  return base.replace(/[-_]/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

const pageIdOf = (p) => (typeof p === 'string' ? p : p && typeof p === 'object' && typeof p.id === 'string' ? p.id : null);

/** Depth-first walk over every group (top-level and nested sub-groups) of a raw sidebar. */
function* walkGroups(items) {
  for (const g of items || []) {
    if (!g || typeof g !== 'object' || pageIdOf(g) !== null) continue;
    yield g;
    if (Array.isArray(g.pages)) yield* walkGroups(g.pages);
  }
}

/** Group by name: top-level groups win, then nested sub-groups in document order. */
function findGroup(sidebar, name) {
  const top = sidebar.find((g) => g && g.group === name);
  if (top) return top;
  for (const g of walkGroups(sidebar)) if (g.group === name) return g;
  return null;
}

/**
 * The group (at any depth) that best matches a page's folder: groups whose listed
 * pages sit directly in `dir` beat groups that only list pages deeper below it;
 * ties go to the innermost (last visited) group.
 */
function inferGroupFor(sidebar, dir) {
  let best = null;
  let bestScore = 0;
  for (const g of walkGroups(sidebar)) {
    if (!Array.isArray(g.pages) || !g.group) continue;
    let score = 0;
    for (const p of g.pages) {
      const id = pageIdOf(p) || '';
      if (!id.startsWith(dir)) continue;
      score = Math.max(score, id.slice(dir.length).includes('/') ? 1 : 2);
    }
    if (score && score >= bestScore) { best = g; bestScore = score; }
  }
  return best;
}

function findListing(sidebar, pageId) {
  for (const g of walkGroups(sidebar)) {
    if (Array.isArray(g.pages) && g.pages.some((p) => pageIdOf(p) === pageId)) return g;
  }
  return null;
}

const isContentTab = (t) => t && typeof t === 'object' && !(typeof t.href === 'string' && t.href.trim());
const tabName = (t) => String(t.tab ?? t.label ?? t.title ?? t.name ?? '');

/** True if the tab's pages come from the file system (autogenerate) and cover this page id. */
function tabAutogenerates(tab, pageId) {
  const dir = normalizeDir(tab.path);
  if (tab.sidebar === 'auto' || (tab.sidebar === undefined && dir)) return !dir || pageId === dir || pageId.startsWith(dir + '/');
  return isAutogeneratedPage(tab.sidebar, pageId);
}

/** Pick the tab a new page belongs to: the named tab, else the one whose `path` covers it, else the first. */
function pickTab(tabs, pageId, wanted) {
  const content = tabs.filter(isContentTab);
  if (wanted) {
    const w = slugify(wanted);
    return content.find((t) => slugify(t.id || tabName(t)) === w || slugify(tabName(t)) === w) || null;
  }
  let best = null;
  for (const t of content) {
    const dir = normalizeDir(t.path);
    if (dir && (pageId === dir || pageId.startsWith(dir + '/')) && (!best || dir.length > normalizeDir(best.path).length)) best = t;
  }
  return best || content[0] || null;
}

/**
 * Add a page id to the raw sidebar in docslit.json (never prints or exits).
 * Returns { status: 'no-config'|'autogenerated'|'unsupported'|'ok', sidebarUpdated, group }.
 * Options: group (name, matched at any nesting depth; default "Pages", or inferred
 * from sibling pages when inferGroup is true), position (1-based index within the
 * group; out of range appends), tab (with "tabs": the tab to add to — by name or id; default:
 * the tab whose "path" covers the page, else the first). Used by `docslit new` and the MCP
 * create_page tool. Extra status: 'unknown-tab'.
 */
export async function addPageToSidebar(cwd, pageId, { group = null, position = null, inferGroup = false, tab = null } = {}) {
  const configPath = path.join(cwd, 'docslit.json');
  if (!await fs.pathExists(configPath)) return { status: 'no-config', sidebarUpdated: false, group: null };
  // Read the raw config (not loadConfig) so autogenerate stays unexpanded on disk.
  const config = await fs.readJson(configPath);
  const tabsMode = Array.isArray(config.tabs) && config.tabs.length > 0;
  let holder = config; // the object that owns the "sidebar" array being edited
  let usedTab = null;
  if (tabsMode) {
    for (const t of config.tabs.filter(isContentTab)) {
      if (tabAutogenerates(t, pageId)) return { status: 'autogenerated', sidebarUpdated: false, group: null, tab: tabName(t) };
      const hit = Array.isArray(t.sidebar) ? findListing(t.sidebar, pageId) : null;
      if (hit) return { status: 'ok', sidebarUpdated: false, group: hit.group || 'Pages', tab: tabName(t) };
    }
    const picked = pickTab(config.tabs, pageId, tab);
    if (!picked) return { status: 'unknown-tab', sidebarUpdated: false, group: null, tab: tab || null };
    if (picked.sidebar !== undefined && !Array.isArray(picked.sidebar)) return { status: 'unsupported', sidebarUpdated: false, group: null };
    holder = picked;
    usedTab = tabName(picked);
  } else {
    if (isAutogeneratedPage(config.sidebar, pageId)) return { status: 'autogenerated', sidebarUpdated: false, group: null };
    if (config.sidebar !== undefined && !Array.isArray(config.sidebar)) return { status: 'unsupported', sidebarUpdated: false, group: null };
  }
  const sidebar = holder.sidebar || [];

  const listed = findListing(sidebar, pageId);
  if (listed) return { status: 'ok', sidebarUpdated: false, group: listed.group || 'Pages', ...(usedTab ? { tab: usedTab } : {}) };

  let entry = group ? findGroup(sidebar, group) : null;
  if (!group && inferGroup && pageId.includes('/')) {
    entry = inferGroupFor(sidebar, pageId.slice(0, pageId.lastIndexOf('/') + 1));
  }
  const groupName = group || entry?.group || 'Pages';
  if (!entry) entry = findGroup(sidebar, groupName);
  if (!entry) {
    entry = { group: groupName, pages: [] };
    sidebar.push(entry);
  }
  let sidebarUpdated = false;
  if (Array.isArray(entry.pages)) {
    const at = Number.isInteger(position) && position >= 1 && position <= entry.pages.length ? position - 1 : entry.pages.length;
    entry.pages.splice(at, 0, pageId);
    holder.sidebar = sidebar;
    await fs.writeFile(configPath, JSON.stringify(config, null, 2) + '\n');
    sidebarUpdated = true;
  }
  return { status: 'ok', sidebarUpdated, group: groupName, ...(usedTab ? { tab: usedTab } : {}) };
}

export async function newPage(args = []) {
  const cwd = process.cwd();
  const json = args.includes('--json');
  const valueFlags = new Set(['--title', '--group', '--description', '--position', '--tab']);
  let pageId = null;
  for (let i = 0; i < args.length; i++) {
    if (valueFlags.has(args[i])) { i++; continue; }
    if (!args[i].startsWith('--')) { pageId = args[i]; break; }
  }

  const fail = (message) => {
    if (json) process.stdout.write(JSON.stringify({ error: message }, null, 2) + '\n');
    else console.error(`  ${pc.red('✗')} ${message}\n`);
    process.exit(1);
  };

  if (!pageId) {
    if (json) fail('Missing page id. Usage: docslit new <page-id> [--title "Title"] [--group "Group"] [--tab "Tab"] [--position <n>] [--description "..."] [--json]');
    console.error('  Usage: docslit new <page-id> [--title "Title"] [--group "Group"] [--tab "Tab"] [--position <n>] [--description "..."] [--json]\n');
    process.exit(1);
  }
  pageId = pageId.replace(/\\/g, '/').replace(/^\/+/, '').replace(/\.md$/, '');

  let title = null;
  let group = null;
  let tab = null;
  let position = null;
  let description = '';
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--title' && args[i + 1]) title = args[++i];
    else if (args[i] === '--group' && args[i + 1]) group = args[++i];
    else if (args[i] === '--tab' && args[i + 1]) tab = args[++i];
    else if (args[i] === '--position' && args[i + 1]) position = args[++i];
    else if (args[i] === '--description' && args[i + 1] !== undefined) description = args[++i];
  }
  title = title || toTitle(pageId);
  if (position !== null && !Number.isFinite(Number(position))) {
    fail('--position must be a number');
  }

  const relFile = `docs/${pageId}.md`;
  const file = path.join(cwd, 'docs', `${pageId}.md`);
  if (await fs.pathExists(file)) fail(`Page already exists: ${relFile}`);
  if (tab) {
    // Fail before writing anything when --tab names a tab that does not exist.
    try {
      const cfg = await fs.readJson(path.join(cwd, 'docslit.json'));
      if (!Array.isArray(cfg.tabs) || !pickTab(cfg.tabs, pageId, tab)) fail(`No tab named "${tab}" in docslit.json`);
    } catch (e) { if (e && e.code !== 'ENOENT') throw e; }
  }

  await fs.ensureDir(path.dirname(file));
  const content = stringifyFrontmatter(`\n# ${title}\n\n`, {
    title,
    description,
    ...(position !== null ? { sidebar_position: Number(position) } : {}),
  });
  await fs.writeFile(file, content);
  if (!json) console.log(`  ${pc.green('✓')} Created ${relFile}`);

  // An explicit sidebar group also gets the page at --position (1-based); the
  // frontmatter sidebar_position above is what orders autogenerated sidebars.
  const sb = await addPageToSidebar(cwd, pageId, { group, tab, position: position !== null ? Number(position) : null });
  if (sb.status === 'autogenerated') {
    if (json) {
      process.stdout.write(JSON.stringify({ id: pageId, file: relFile, sidebarUpdated: false, group: null, autogenerated: true }, null, 2) + '\n');
      return;
    }
    console.log(`  ${pc.green('✓')} Sidebar is autogenerated — page will appear automatically`);
    console.log(`\n  Edit the page, then run ${pc.cyan('docslit dev')}.\n`);
    return;
  }
  if (sb.status === 'unsupported') {
    if (json) {
      process.stdout.write(JSON.stringify({ id: pageId, file: relFile, sidebarUpdated: false, group: null }, null, 2) + '\n');
      return;
    }
    console.log(`  ${pc.yellow('!')} Unrecognised sidebar format — not updated`);
    return;
  }
  const sidebarUpdated = sb.sidebarUpdated;
  const usedGroup = sb.group;
  if (sidebarUpdated && !json) console.log(`  ${pc.green('✓')} Added to ${sb.tab ? `tab "${sb.tab}", ` : ''}sidebar group "${usedGroup}"`);

  if (json) {
    process.stdout.write(JSON.stringify({ id: pageId, file: relFile, sidebarUpdated, group: usedGroup, ...(sb.tab ? { tab: sb.tab } : {}) }, null, 2) + '\n');
    return;
  }
  console.log(`\n  Edit the page, then run ${pc.cyan('docslit dev')}.\n`);
}
